// 마무리 이미지 삽입 — 매뉴얼 PART 2-4 ⑦단계
// 🔒 v1 (2026.04): 본문 마무리 섹션 안에 이미지 마크다운 1줄 삽입
//   - 위치: ## 마무리 헤더 직후, 첫 단락 다음
//   - 이미지 src는 비워두고 alt만 — 사용자가 네이버 블로그에 붙여넣을 때
//     붙여넣은 사진과 자연스럽게 짝지어지도록 alt 자리만 마련
//   - alt는 활성 부위·치료명을 반영해 SEO 효과 (getImageAlts 첫 항목 사용)
//   - "사진 첨부란"이 이걸로 마련됨 — 사용자가 네이버에서 사진을 끼워 넣으면 됨
// ──────────────────────────────────────────────────────────────
function insertClosingImage(text, imageAlts) {
  if (!Array.isArray(imageAlts) || imageAlts.length === 0) return text;

  // 이미지 마크다운 — alt만 채운 빈 src
  // 네이버 블로그 붙여넣기용: 사진 자리 표시 + alt 텍스트 SEO
  const imgLine = `\n![${imageAlts[0]}](사진을_여기에_첨부하세요)\n`;

  // ## 마무리 헤더 위치 찾기
  const closingRe = /(^|\n)## 마무리\b[^\n]*\n/;
  const m = closingRe.exec(text);
  if (!m) {
    // 헤더 못 찾으면 글 끝에 부착 (보험)
    return text + imgLine;
  }

  // 헤더 직후 첫 단락 끝 위치 찾기 — 헤더 바로 뒤 첫 줄바꿈 2개 또는 글 끝
  const headerEnd = m.index + m[0].length;
  const afterHeader = text.slice(headerEnd);
  // 첫 단락 끝(\n\n) 위치
  const paraEnd = afterHeader.search(/\n\n/);

  if (paraEnd === -1) {
    // 마무리 단락이 한 덩어리 → 끝에 붙이기
    return text + imgLine;
  }

  // 첫 단락 끝 직후에 이미지 삽입
  const insertAt = headerEnd + paraEnd;
  return text.slice(0, insertAt) + imgLine + text.slice(insertAt);
}

// 보조: 제목 패턴 랜덤 선택
function pickTitle(treatment, region) {
  const patterns = treatment.titlePatterns || [`{region} ${treatment.name} 후기`];
  const pick = patterns[Math.floor(Math.random() * patterns.length)];
  return pick.replace('{region}', region);
}

// 보조: fullKeyword 3회 미만이면 마무리 섹션 앞에 자연 삽입
// 🔒 v2 (2026.04): CTA 제거, 5개 정보형 풀에서 랜덤 선택
//   - "알아보시는 것도 좋아요", "상담 받아보세요" 등 권유·CTA 표현 전면 제거
//   - 풀 5개에서 부족분만큼 중복 없이 뽑아 자연 분산
// 🔒 v1.3 (2026.05): 보강 문장 최대 1개로 제한 — AI 패턴 차단
//   원인: need가 3 이상일 때 보강 문장 3개가 한 줄에 이어붙어 AI 글 티 명백
//   처리: 본문이 짧지 않은 한 1개만 삽입, 충분한 줄바꿈으로 자연스럽게 분리
function ensureFullKeyword(text, fullKeyword, minCount) {
  const re = new RegExp(escapeRegex(fullKeyword), 'g');
  const count = (text.match(re) || []).length;
  if (count >= minCount) return text;

  // v1.3: 최대 1개만 삽입 — 여러 문장 이어붙이면 AI 패턴 노출
  const POOL = [
    `${fullKeyword} 관련 사례를 찾아보면 비슷한 경우가 많다고 하더라고요.`,
    `${fullKeyword} 기준으로 보면 비슷한 치료 흐름이 반복된다고 해요.`,
    `${fullKeyword} 사례 비교 자료를 보면 판단 기준이 명확해지더라고요.`,
    `${fullKeyword} 관련 글에서 결정 과정이 비슷하게 정리되어 있더라고요.`,
    `${fullKeyword} 정보를 찾아보면서 비슷한 경험담을 많이 봤어요.`,
  ];

  const pick = POOL[Math.floor(Math.random() * POOL.length)];
  const block = '\n\n' + pick + '\n\n';

  const closingIdx = text.lastIndexOf('## 마무리');
  if (closingIdx === -1) return text + block;
  return text.slice(0, closingIdx) + block + text.slice(closingIdx);
}

// 보조: 해시태그 6개
function buildHashtags({ region, activeKeyword, treatmentName }) {
  const tags = [
    `#${region}산부인과`,
    `#${region}${treatmentName}`,
    `#${activeKeyword.replace(/\s/g, '')}`,
    `#${treatmentName}후기`,
    `#${region}${treatmentName}후기`,
    `#산부인과후기`,
  ];
  // 중복 제거
  return [...new Set(tags)].slice(0, 6).join(' ');
}
