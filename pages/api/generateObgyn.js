// 정보블럭 삽입 — 결정 섹션 아래 고정 (매뉴얼 PART 2-1)
// 🔒 v3 (2026.04): H2 정확 매칭 + 다음 섹션 라벨 fallback
//   - 결정 섹션 내부에 GPT가 H3을 끼워 넣어도 흔들리지 않게
//   - "## 치료 결정" 의 다음 H2 ("## 치료 후 변화") 시작 직전에 삽입
// 🔒 v4 (2026.04): 카테고리별 분기
//   - cat 인자 추가 (treatment.cat 그대로) → 해당 풀에서만 선택
//   - 풀 없으면 default로 폴백
//   - 삼차신경통 글에 "척추 통증 진료 단계" 표가 박히던 사고 차단
// ──────────────────────────────────────────────────────────────
function insertInfoBlock(text, decisionAnchor = '치료 결정', cat = null) {
  // 카테고리별 풀 선택 — 매칭 실패 시 default로 폴백
  const blocks = (cat && INFO_BLOCKS[cat]) || INFO_BLOCKS.default;
  const block = blocks[Math.floor(Math.random() * blocks.length)];
  const md = renderBlockAsMarkdown(block);

  // H2 시작 위치만 정확히 찾기 — H3는 무시
  // 🔒 v8 (2026.04): \b 제거 — 한글 뒤 word boundary 매칭 실패 차단
  //   (^|\n)## 치료 결정\b 가 ## 치료 결정이 첫 줄(offset 0)이면 매칭 실패하는 버그
  //   해결: \b → (?=\s|$) 로 교체 (공백·줄바꿈·문서끝 중 하나로 종결)
  const findH2 = (label) => {
    const re = new RegExp(`(^|\\n)## ${escapeRegex(label)}(?=\\s|$)`, 'm');
    const m = re.exec(text);
    return m ? m.index + (m[1] === '\n' ? 1 : 0) : -1;
  };

  const decisionIdx = findH2(decisionAnchor);
  if (decisionIdx === -1) {
    // 앵커 없으면 마무리 직전에 삽입
    const closingIdx = findH2('마무리');
    if (closingIdx === -1) return text + '\n\n' + md + '\n';
    return text.slice(0, closingIdx) + md + '\n\n' + text.slice(closingIdx);
  }

  // 결정 섹션 다음 H2 찾기 — '치료 후 변화' 우선, 없으면 임의 H2
  let nextH2 = findH2('치료 후 변화');
  if (nextH2 === -1 || nextH2 < decisionIdx) {
    // 결정 섹션 이후의 첫 H2 찾기
    const re = /\n## /g;
    re.lastIndex = decisionIdx + 1;
    const m = re.exec(text);
    nextH2 = m ? m.index + 1 : -1;
  }

  // 🔒 v5 (2026.04): H2 fallback — 치료 후 변화 H2가 누락된 경우
  //   GPT가 ## 치료 후 변화 H2를 빠뜨리고 ### 1일부터 시작하면 nextH2가 ## 마무리가 됨
  //   → 비교표가 마무리 안에 박히고 이미지가 비교표 뒤로 밀리는 사고
  //   해결: 결정 섹션 이후 첫 ### 1일 (또는 첫 ###) 위치를 찾아서 그 앞에 삽입
  if (nextH2 === -1 || (findH2('마무리') !== -1 && nextH2 === findH2('마무리'))) {
    // 결정 이후 첫 ### 헤더 위치 (### 1일 / ### 1주 등)
    const h3Re = /\n### /g;
    h3Re.lastIndex = decisionIdx + 1;
    const h3m = h3Re.exec(text);
    if (h3m) {
      const h3Idx = h3m.index + 1;
      // ### 1일이 마무리 H2 이전에 있으면 그 앞에 삽입
      const closingIdx = findH2('마무리');
      if (closingIdx === -1 || h3Idx < closingIdx) {
        nextH2 = h3Idx;
      }
    }
  }

  if (nextH2 === -1) {
    // 다음 H2가 없으면 텍스트 끝에 삽입
    return text + '\n\n' + md + '\n';
  }

  return text.slice(0, nextH2) + md + '\n\n' + text.slice(nextH2);
}

function renderBlockAsMarkdown(block) {
  const header = `### ${block.title}`;
  const headerRow = block.rows[0];
  const colCount = headerRow.length;
  const sep = `|${' --- |'.repeat(colCount)}`;
  const lines = [header, '', `| ${headerRow.join(' | ')} |`, sep];
  for (let i = 1; i < block.rows.length; i++) {
    lines.push(`| ${block.rows[i].join(' | ')} |`);
  }
  return lines.join('\n');
}

