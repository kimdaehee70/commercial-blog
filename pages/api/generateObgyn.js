// 중복 제거 — 섹션·문단·문장 3단계 + 🔒 v7: 줄 단위 4단계
//   v7 변경:
//   - 짧은 문장(10자 미만)도 중복 검출 (이전엔 통과시킴)
//   - 마침표 없는 줄도 중복 검출 (split이 마침표만 봐서 누락되던 케이스)
//   - 정규화 비교 (공백·구두점 무시한 핵심 텍스트로 비교)
function removeDuplicates(text) {
  // 섹션 단위
  const sections = text.split(/\n## /);
  const seenSec = new Set();
  const uniqSec = [];
  sections.forEach((s, i) => {
    const head = s.split('\n')[0].slice(0, 30);
    if (i > 0 && seenSec.has(head)) return;
    seenSec.add(head);
    uniqSec.push(s);
  });
  let t = uniqSec.join('\n## ');

  // 문단 단위
  const paras = t.split(/\n{2,}/);
  const seenPara = new Set();
  const uniqPara = paras.filter(p => {
    const k = p.trim().slice(0, 60);
    if (!k) return false;
    if (seenPara.has(k)) return false;
    seenPara.add(k);
    return true;
  });
  t = uniqPara.join('\n\n');

  // 🔒 v7: 줄 단위 중복 제거 — 마침표 없는 짧은 줄도 검출
  //   "후기 수 + 장비 기준 선택"처럼 마침표 없이 끝나는 줄이 같은 섹션 안에서
  //   2번 등장하는 케이스를 잡기 위함
  const lines = t.split('\n');
  const seenLine = new Set();
  const uniqLine = lines.filter(line => {
    // 헤더(##/###), 표(|), 빈 줄은 통과
    if (/^(##|###|####)/.test(line.trim())) return true;
    if (line.trim().startsWith('|')) return true;
    if (line.trim() === '') return true;
    // 정규화 키 — 공백·문장부호 제거 후 비교
    const norm = line.trim().replace(/[\s.,!?·…+\-]/g, '');
    if (norm.length < 6) return true; // 너무 짧으면 통과 (의미 손실 방지)
    if (seenLine.has(norm)) return false;
    seenLine.add(norm);
    return true;
  });
  t = uniqLine.join('\n');

  // 문장 단위 (마침표 기준 split)
  const sents = t.split(/(?<=[.!?])\s+/);
  const seenSent = new Set();
  const uniqSent = sents.filter(s => {
    const k = s.trim();
    if (k.length < 10) return true;
    // 정규화 키 — 줄 단위와 동일 기준
    const norm = k.replace(/[\s.,!?·…+\-]/g, '');
    if (seenSent.has(norm)) return false;
    seenSent.add(norm);
    return true;
  });
  return uniqSent.join(' ');
}

