function removeConsecutive(text, words) {
  let t = text;
  for (const w of words) {
    let count = 0;
    const re = new RegExp(escapeRegex(w), 'g');
    t = t.replace(re, m => (++count > 1 ? '' : m));
  }
  return t;
}

// 🔒 v7 (2026.04): 문맥 기반 안전 치환
//   - 치환어 뒤에 잘못된 조사가 남는 문제 ('해당 진료이 의심') 차단
//   - 시간 한정사('이번') 뒤 명사 직결 차단 ('이번 진료 전문가')
//   - 치환 후 조사가 자동 정리되도록 처리
function limitKeywordRepeat(text, keyword, max) {
  const re = new RegExp(escapeRegex(keyword), 'g');
  const matches = text.match(re);
  if (!matches || matches.length <= max) return text;

  // 치환어 풀 — 라벨별로 뒤따를 수 있는 조사·문맥 차이 있음
  // - '이 치료', '해당 치료', '치료': 일반 명사구로 동작
  // 🔒 v8 (2026.04): '이번 진료' 제거 — 시간 한정사라 "강남 이번 진료" 같은 어색 표현 발생
  //   '진료'보다는 시술 글이라 '치료'가 더 자연스러움 → '치료' 계열로 통일
  const REPLACEMENTS = ['이 치료', '해당 치료', '시술', '치료'];

  let count = 0;
  return text.replace(re, (m, offset, full) => {
    count++;
    if (count <= max) return m;

    // 인접 5글자 윈도우 검사 — '치료/시술/수술/요법' 단어 충돌 방지
    const before = full.slice(Math.max(0, offset - 5), offset);
    const after  = full.slice(offset + m.length, offset + m.length + 5);
    const ctx = before + after;

    // 충돌 단어 후보 — 이 단어가 인접하면 치환 스킵
    const COLLISION = ['치료', '시술', '수술', '요법', '진료'];
    const hasCollision = COLLISION.some(c => ctx.includes(c));
    if (hasCollision) {
      // 충돌하면 치환 자체를 스킵 (원본 유지) — "이 치료 치료" 같은 어색함 방지
      return m;
    }

    // 🔒 v10 (2026.04): 동사 직전 치환 차단 — 의미 깨짐 방지
    //   "편두통이 발생할" → "치료가 발생할" 같은 사고 차단
    //   키워드 직후 [조사 + 동사어간] 패턴이면 치환 스킵
    const afterLong = full.slice(offset + m.length, offset + m.length + 10);
    const VERB_AFTER = /^(이|가|을|를|은|는|로|으로)?\s*(발생|시작|반복|악화|호전|완화|증가|감소|지속|재발|나타나|보이|느껴|생기|일어나|찾아오)/;
    if (VERB_AFTER.test(afterLong)) {
      return m;
    }

    // 🔒 v7 가드 1: 키워드 직후 글자가 받침 있는 명사 + '이' 조사인 경우
    //    원본이 잘못된 조사로 끝나는 경우 ("고주파신경치료이 의심" → "해당 진료이 의심" 비문)
    //    키워드 직후 1~2글자 안에 잘못된 조사가 있으면 치환 스킵 (원본도 비문이지만, 치환하면 더 명백한 비문이 됨)
    const afterChar = full[offset + m.length] || '';
    const afterChar2 = full[offset + m.length + 1] || '';
    // 키워드 마지막 글자가 받침 없음(예: '료')인데 직후가 '이'면 잘못 붙은 조사
    const lastKwChar = m[m.length - 1];
    const lastCode = lastKwChar.charCodeAt(0) - 0xAC00;
    const lastHasJongseong = lastCode >= 0 && lastCode < 11172 && (lastCode % 28) !== 0;
    if (!lastHasJongseong && afterChar === '이' && /[\s가-힣]/.test(afterChar2)) {
      // 받침 없는데 '이'가 붙음 → 원본 비문 → 치환 스킵 (원본 유지가 차라리 안전)
      return m;
    }

    // 🔒 v7 가드 2: 시간 한정사 '이번 진료' 회피
    //    '이번 진료' 뒤에 '전문가/병원/원장' 같은 명사가 직결되면 비문
    //    예: "강남 이번 진료 전문가" → 어색
    //    이런 위치면 '이 진료'/'해당 진료' 같은 일반형으로 강제 선택
    const NOUN_AFTER = /^(\s*)(전문가|병원|원장|선생|의료진|기관|센터|클리닉)/;
    const nounDirectlyAfter = NOUN_AFTER.test(after);

    // 안전한 치환어 선택 (라운드로빈 + 가드 적용)
    let pick = REPLACEMENTS[(count - max) % REPLACEMENTS.length];
    if (nounDirectlyAfter && pick === '이번 진료') {
      // '이번 진료 전문가' 비문 방지 — '해당 진료'로 강제 변경
      pick = '해당 진료';
    }
    return pick;
  });
}

// 🔒 v7 보조: 치환 결과 후속 정리 — 잘못된 조사·공백 정리
//   '해당 치료이' → '해당 치료가'
//   '이 치료을' → '이 치료를'
//   '치료은' → '치료는'
// 🔒 v8 (2026.04): 치환어 풀 변경(진료→치료 계열)에 맞춰 재작성
function fixReplacementJosa(text) {
  let t = text;
  // 받침 없는 '료'(받침 없음) + 잘못 붙은 조사 교정 — 치료/시술 모두 받침 없음
  t = t.replace(/(이 치료|해당 치료|치료|시술)이(\s|,|\.|$)/g, '$1가$2');
  t = t.replace(/(이 치료|해당 치료|치료|시술)을(\s|,|\.|$)/g, '$1를$2');
  t = t.replace(/(이 치료|해당 치료|치료|시술)은(\s|,|\.|$)/g, '$1는$2');
  // 🔒 v10b (2026.04): 역방향 — 받침없는 명사에 받침조사가 잘못 붙은 경우
  //   "비수술적 시술를" → "비수술적 시술을" X — 시술은 받침없으니 "를"이 맞음
  //   하지만 GPT가 "치료를" 자리에 "시술를"로 만든 경우는 사실 정상 (받침없음+를)
  //   진짜 문제: "시술는" / "치료는" 이 받침없으니 "는"이 정상이고 OK
  //   그러나 결과물 "비수술적 시술는" → "시술" 받침없음 + "는"은 자연 → 이미 OK
  //   ★ 진짜 사고: "시술를" 받침없음에 "를"은 정상이지만, 원문이 "시술을"이었는데 GPT가 "을"을 붙임
  //              "비수술적 시술을" 자체는 정상. "시술를" 도 정상. 둘 다 OK
  //   따라서 추가 보정 없음 — 결과물의 "시술를"은 사실 문법적으로 정상

  // 🔒 v10 (2026.04): 받침없는 치환어 + 으로/이라/이고/이며 → 로/라/고/며
  t = t.replace(/(이 치료|해당 치료|치료|시술)으로(\s|,|\.|$)/g, '$1로$2');
  t = t.replace(/(이 치료|해당 치료|치료|시술)이라(\s|,|\.|$)/g, '$1라$2');
  t = t.replace(/(이 치료|해당 치료|치료|시술)이고(\s|,|\.|$)/g, '$1고$2');
  t = t.replace(/(이 치료|해당 치료|치료|시술)이며(\s|,|\.|$)/g, '$1며$2');
  // 🔒 v7 보조: 이전 버전 잔재 — '이번 진료/해당 진료' 등 진료 계열도 같이 정리 (혹시 남아있을 경우)
  t = t.replace(/(이 진료|해당 진료|이번 진료|진료)이(\s|,|\.|$)/g, '$1가$2');
  t = t.replace(/(이 진료|해당 진료|이번 진료|진료)을(\s|,|\.|$)/g, '$1를$2');
  t = t.replace(/(이 진료|해당 진료|이번 진료|진료)은(\s|,|\.|$)/g, '$1는$2');
  t = t.replace(/이번 진료\s+(전문가|병원|원장|선생|의료진|기관|센터|클리닉)/g, '해당 치료의 $1');
  // 🔒 v9 (2026.04): "이 치료 문제" / "해당 치료 문제" 어색함 차단
  t = t.replace(/(이 치료|해당 치료|치료|시술)\s+문제/g, '이 문제');
  t = t.replace(/(이 치료|해당 치료|치료|시술)\s+증상/g, '증상');
  // 🔒 v10 (2026.04): "강남 시술으로 이라" 같은 깨짐 정리
  t = t.replace(/(이 치료|해당 치료|치료|시술)으로\s+이라/g, '$1라');
  t = t.replace(/(이 치료|해당 치료|치료|시술)\s+이라/g, '$1라');
  // 🔒 v10b (2026.04): 비수술적 시술를/시술는 등 어색함 정리 — 시술 앞 '비수술적' 같은 수식어
  t = t.replace(/비수술적\s+시술/g, '비수술 치료');
  return t;
}

