// ★ buildDermaTitle — mode 분기 + 광고 어휘 자동 필터링
// ============================================================
function buildDermaTitle(treatment, region, blogTypeId, mode) {
  const validMode = (mode === "commercial") ? "commercial" : "personal";
  const name = treatment.name;

  const titleIdx = Math.floor(Math.random() * (treatment.titlePatterns?.length || 1));
  let titleRaw = (treatment.titlePatterns?.[titleIdx] || "{region} {name} 후기")
    .replace("{region}", region)
    .replace("{name}", name);

  if (validMode === "commercial") {
    // commercial — 정보형 제목으로 변환
    titleRaw = titleRaw
      .replace(/후기/g, "정보 안내")
      .replace(/솔직/g, "")
      .replace(/추천/g, "안내")
      .replace(/만족/g, "")
      .replace(/꼭/g, "")
      .replace(/대박/g, "")
      .replace(/극복기/g, "안내")
      .replace(/이야기/g, "안내")
      .replace(/\s+/g, " ")
      .trim();
    if (!titleRaw.includes("안내") && !titleRaw.includes("정보")) {
      titleRaw = region + " " + name + " 정보 안내";
    }
  } else {
    // personal — 광고 어휘 자동 필터링
    const adWords = ["솔직", "추천", "만족", "꼭", "대박", "극복", "강력"];
    let hasAd = adWords.some(w => titleRaw.includes(w));
    if (hasAd) {
      // 다른 패턴으로 재선택 시도
      for (const p of (treatment.titlePatterns || [])) {
        const candidate = p.replace("{region}", region).replace("{name}", name);
        if (!adWords.some(w => candidate.includes(w))) {
          titleRaw = candidate;
          break;
        }
      }
      // 여전히 광고어 있으면 단어 제거
      adWords.forEach(w => { titleRaw = titleRaw.replace(new RegExp(w, "g"), ""); });
      titleRaw = titleRaw.replace(/\s+/g, " ").trim();
    }
  }

  return titleRaw;
}

