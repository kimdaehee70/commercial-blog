function countCommercialViolations(text) {
  const counts = {
    EFFECT_WORDS:  0,
    CTA_WORDS:     0,
    REVIEW_TONE:   0,
    FIRST_PERSON:  0,
    PRICE_BAIT:    0,
    CLINIC_PRAISE: 0,
  };
  for (const [cat, regs] of Object.entries(DERMA_BLOCK_MAP)) {
    for (const r of regs) {
      const m = text.match(r);
      if (m) counts[cat] += m.length;
    }
  }
  counts.total = Object.values(counts).reduce((a, b) => a + b, 0);
  return counts;
}

