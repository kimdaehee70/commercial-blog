  t = t.replace(/(강조했음|강조함|강조됨)\.?/g, "설명됨.");
  t = t.replace(/도움을?\s*돕는/g, "변화를 돕는");

  // ★ 감정 표현 / AI 흔적 제거
  t = t.replace(/긍정적인\s*신호/g, "일반적으로 나타나는 변화");
  t = t.replace(/긍정적인\s*경험/g, "일반적인 변화 사례");
  t = t.replace(/긍정적인\s*변화/g, "체감되는 변화");
  t = t.replace(/긍정적으로\s*받아들여(짐|진다|졌|진|진다는)/g, "일반적인 변화로 해석$1");

  // ★ 마지막 문단 약한 표현 → 강한 표현
