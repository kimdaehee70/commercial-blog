  t = t.replace(/가능성이?\s*보임\.?/g, "실제 변화로 이어지는 경우가 있음.");
  t = t.replace(/가능성이?\s*있어\s*보임\.?/g, "실제 변화로 이어지는 경우가 있음.");

  // ★ 광고톤 경계선 표현 약화 (의료광고법 안전권 강화)
  t = t.replace(/효과적일?\s*수\s*있는\s*이유로/g, "변화가 나타날 수 있는 기전으로");
