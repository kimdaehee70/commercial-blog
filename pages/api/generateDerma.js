// ★ "관찰됨/확인됨/나타남" 반복 분산 (각 2회 초과 시 변형 — 강도 ↑)
// ============================================================
function spreadDermaObservation(text) {
  let t = text;

  // "확인됨" 2회 초과 시 변형 (v3.7: 조사 충돌 위험 어휘 제거)
  const confirmVariants = [
    "정리됨",
    "나타남",
    "체감되는 흐름이 보임",
    "실제 변화로 이어지는 경우가 있음",
    "선택 기준으로 작용함",
    "정리되는 양상이 보임",
  ];
  let confirmCount = 0;
  let cvIdx = 0;
  t = t.replace(/확인됨/g, (m) => {
    confirmCount++;
    if (confirmCount <= 2) return m;
    const v = confirmVariants[cvIdx % confirmVariants.length];
    cvIdx++;
    return v;
  });

  // "관찰됨" 2회 초과 시 변형 (v3.7: '변화가 이어짐' 제거 — 앞 단어 + 조사 충돌 원인)
  const observeVariants = [
    "보임",
    "흐름이 보임",
    "정리되는 양상이 보임",
    "경향이 보임",
    "참고되는 요소로 작용함",
    "양상이 보임",
  ];
  let observeCount = 0;
  let ovIdx = 0;
  t = t.replace(/관찰됨/g, (m) => {
    observeCount++;
    if (observeCount <= 2) return m;
    const v = observeVariants[ovIdx % observeVariants.length];
    ovIdx++;
    return v;
  });

  // "나타남" 3회 초과 시 변형 (v3.7: '변화로 이어짐' 제거)
  const appearVariants = [
    "이어짐",
    "흐름이 보임",
    "양상이 보임",
    "정리되는 모습이 보임",
  ];
  let appearCount = 0;
  let avIdx = 0;
  t = t.replace(/나타남(?!\S)/g, (m) => {
    appearCount++;
    if (appearCount <= 3) return m;
    const v = appearVariants[avIdx % appearVariants.length];
    avIdx++;
    return v;
  });

  // "도움이 될 수 있음" → "도움으로 작용하는 경우가 있음" 변형
  const helpVariants = [
    "도움으로 작용하는 경우가 있음",
    "참고되는 요소로 작용함",
    "선택 기준으로 작용함",
  ];
  let helpCount = 0;
  let hvIdx = 0;
  t = t.replace(/도움이?\s*될\s*수\s*있음/g, (m) => {
    helpCount++;
    if (helpCount <= 1) return m;
    const v = helpVariants[hvIdx % helpVariants.length];
    hvIdx++;
    return v;
  });

  // "가능함" 단독 어미 → "선택 기준으로 작용함" 변형
  const possibleVariants = [
    "선택 기준으로 작용함",
    "참고 요소로 정리됨",
    "비교 기준이 됨",
  ];
  let possibleCount = 0;
  let pvIdx = 0;
  t = t.replace(/(?<![가-힣])가능함\.?/g, (m) => {
    possibleCount++;
    if (possibleCount <= 2) return m;
    const v = possibleVariants[pvIdx % possibleVariants.length];
    pvIdx++;
    return v + ".";
  });

  return t;
}

