  t = t.replace(/(건조함|따가움|홍조|붉은\s*기|민감함|자극감)이?\s*흐름이?\s*보임\.?/g, "$1이 관찰됨.");

  // ★★★ v3.8: 합성 깨짐 패턴 — finalPainClean 결과 + 잔존 어미 충돌 ★★★
  // "실제 변화로 이어지는 경우가 있음.이 정리됨." — 마침표 직후 '이 정리됨' 잔존
  // "있음" → "있는" 어미 변환 + ".이" 제거
  t = t.replace(/(있|있었)음\.\s*이\s*정리됨\.?/g, "$1는 것으로 정리됨.");
  t = t.replace(/(있|있었)음\.\s*이\s*확인됨\.?/g, "$1는 것으로 확인됨.");
  t = t.replace(/(있|있었)음\.\s*이\s*보임\.?/g, "$1는 것으로 보임.");
  // 일반화: "~음." 뒤에 "이 정리됨/확인됨/보임" 단독 (위 케이스 외)
  t = t.replace(/(됨)\.\s*이\s*(정리됨|확인됨|보임|나타남)\.?/g, "$1, 이는 $2.");

  // ─── D. 1개월 광고톤 (깨끗해지는 방향) ───────────────────────
  t = t.replace(/피부가?\s*전반적으로?\s*깨끗해지는?\s*방향으로?\s*진행되고?\s*있음이?\s*보임\.?/g,
    "피부가 전반적으로 정돈되는 양상이 보임.");
  t = t.replace(/깨끗해지는?\s*방향으로?/g, "정돈되는 양상으로");

  // ─── E. 마무리 약한 표현 (재발 가드) ──────────────────────────
  // "유용할 수 있는 방법으로 보임" / "유용할 수 있는 시술로 보임"
  t = t.replace(/유용할?\s*수\s*있는?\s*(방법|방안|시술|선택지)으로?\s*보임\.?/g,
    "실제 변화로 이어지는 경우가 있음.");
  t = t.replace(/유용할?\s*수\s*있는?\s*(방법|방안|시술|선택지)으로?\s*보인다\.?/g,
    "실제 변화로 이어지는 경우가 있다.");

  // ─── F. 받침 조사 오류 (재발 가드) ────────────────────────────
  // ★ v3.10 수정: 진료처는 '를'이 정답
  t = t.replace(/(기관|의료기관)를(?=\s)/g, "$1을");
  t = t.replace(/진료처을(?=\s|[.,])/g, "진료처를");

  // ─── G. 어미 절단 (재발 가드) ──────────────────────────────────
  t = t.replace(/나타\s+(피부|경우|상태|반응|단계|양상|흐름|변화|시기|때|구간|국면|시점|염증|여드름|트러블|증상|문제|징후|현상|모습|결과|기간|것|데)/g, "나타나는 $1");
  // ★ v3.8: 형용사+명사 직전 "나타" (final 단독에서도 가드)
  t = t.replace(/나타\s+(일시적인|일반적인|경미한|미세한|뚜렷한|점진적인|간헐적인|새로운|반복적인|전형적인)\s+(반응|증상|현상|변화|모습|양상|결과|상태|패턴|흐름|건조함|따가움|홍조|자극|불편|민감함|가려움)/g,
    "나타나는 $1 $2");
  // ★ v3.9: 다른 동사 어미 절단 — "늘어/줄어/달라" + 명사
  t = t.replace(/늘어\s+(추세|경향|양상|흐름|패턴)/g, "늘어나는 $1");
  t = t.replace(/줄어\s+(추세|경향|양상|흐름|패턴)/g, "줄어드는 $1");
  t = t.replace(/달라\s+(양상|흐름|패턴|방향)/g, "달라지는 $1");
  // ★ v3.8: 형용사+명사 직전 "나타" 단독 (일시적인/일반적인/경미한 등)
  t = t.replace(/나타\s+(일시적인|일반적인|경미한|미세한|뚜렷한|점진적인|간헐적인|초기의?|중기의?|기존의?|새로운|반복적인|전형적인)\s+(반응|증상|현상|변화|모습|양상|결과|상태|패턴|흐름|건조함|따가움|홍조|자극|불편|민감함|가려움)/g,
    "나타나는 $1 $2");

  // ─── H. 광고톤 단독 어미 (재발 가드) ──────────────────────────
  t = t.replace(/(?<![가-힣])판단됨\.?/g, "정리됨.");

  // ─── I. v3.12: AI 클로즈 빈도 차단 ──────────────────────────────
  // "보임" / "정리됨" / "체감" / "이어지는 경우" — AI가 자주 쓰는 4대 클로즈
  // 글 안에서 4회 초과 사용 시 변형 분산
  // 단, 첫 N개는 보존 (자연스러움 유지)

  // "정리됨" — 4회 초과 변형 (단어 경계: 마침표/공백/문장끝 직전)
  const summaryVariants = [
    "확인됨",
    "관찰됨",
    "기록됨",
    "검토됨",
    "파악됨",
  ];
  let summaryCount = 0;
  let svIdx = 0;
  t = t.replace(/정리됨(?=[.\s,]|$)/g, (m) => {
    summaryCount++;
    if (summaryCount <= 3) return m;
    const v = summaryVariants[svIdx % summaryVariants.length];
    svIdx++;
    return v;
  });

  // "보임" 단독 어미 — 4회 초과 변형 (음슴체)
  // "흐름이 보임" / "양상이 보임" 같이 앞에 단어 있는 경우만 변형
  const seenVariants = [
    "확인됨",
    "관찰됨",
    "기록됨",
    "정리됨",
  ];
  let seenCount = 0;
  let snIdx = 0;
  t = t.replace(/(흐름|양상|경향|모습|상태|변화|움직임)이?\s+보임(?=[.\s,]|$)/g, (m, p1) => {
    seenCount++;
    if (seenCount <= 3) return m;
    const v = seenVariants[snIdx % seenVariants.length];
    snIdx++;
    return p1 + "이 " + v;
  });

  // "체감" 동사 종결 — 4회 초과 변형
  // "체감됨" / "체감되었음" / "체감할 수 있었음"
  const feelVariants = [
    "확인됨",
    "관찰됨",
    "변화가 정리됨",
    "변화가 기록됨",
  ];
  let feelCount = 0;
  let fvIdx = 0;
  t = t.replace(/체감(됨|되었음|할\s*수\s*있었음|되는\s*변화가?\s*있었음)\.?/g, (m) => {
    feelCount++;
    if (feelCount <= 3) return m;
    const v = feelVariants[fvIdx % feelVariants.length];
    fvIdx++;
    return v + ".";
  });

  // "이어지는 경우가 있음" — 광고톤 반복 차단 (이미 v3.11 fix에서 처리됨)
  // 추가 가드: final 단계에서도 한번 더 분산 카운트
  let chainCount = 0;
  t = t.replace(/이어지는?\s*경우가?\s*있음\.?/g, (m) => {
    chainCount++;
    if (chainCount <= 1) return m;
    const variants = ["확인되는 경우가 있음.", "변화가 정리되는 경우가 있음.", "관찰되는 사례가 있음."];
    return variants[(chainCount - 2) % variants.length];
  });

  // ============================================================
  // ★★★ v4: GPT 9단계 통합 필터 (적용 순서 중요) ★★★
  // 순서: N(1주/2주 가이드 먼저) → O(마무리 공식) → J(광고톤) → K(흐름 금지) → L(잔존 정리) → M(빈도 차단)
  // ============================================================

  // ─── N. v4: 1주/2주 시점 정확성 가이드 (가장 먼저) ──────────
  // ★ pain 도메인 1주 의학 가이드: 통증 즉시 사라짐은 부적절 → 시술 부위 염증·자극이 먼저
  // "1주차에 통증이 사라짐/없어짐/소실됨" — 의학 오류
  t = t.replace(
    /### 1주\s*\n([^#]*?)일주일\s*(?:정도\s*)?지나면서?\s*통증이?\s*(?:완전히|거의|전부|싹|모두)?\s*(?:사라|없어|소실|없어지|사라지)\S*/g,
    "### 1주\n$1일주일 정도 지나면서 시술 부위 염증과 자극이 먼저 가라앉는 흐름이 나타나기 시작함"
  );
  // "1주차에 통증이 즉각 줄어든/즉시 호전된" 등 즉각 단정
  t = t.replace(
    /### 1주\s*\n([^#]*?)일주일\s*(?:정도\s*)?지나면서?\s*통증이?\s*(?:즉각|즉시|확실히|뚜렷이)\s*(?:줄어|감소|호전|개선|완화)\S*/g,
    "### 1주\n$1일주일 정도 지나면서 시술 부위 염증·자극이 먼저 가라앉는 흐름이 나타나기 시작함"
  );
  // "1주차에 가동범위 완전 회복" 등
  t = t.replace(
    /### 1주\s*\n([^#]*?)일주일\s*(?:정도\s*)?지나면서?\s*가동범위가?\s*(?:완전히|확실히|크게)\s*(?:회복|개선|돌아|회복됨|회복되|회복하)\S*/g,
    "### 1주\n$1일주일 정도 지나면서 가동범위 일부에서 완만한 변화가 나타나기 시작함"
  );

  // ─── (derma 잔존 가이드 — pain에서는 매칭 안 되지만 호환성 유지) ──
  // 1주: "여드름 개수가 조금씩 달라지는 흐름" — 의학 오류 (derma)
  t = t.replace(
    /### 1주\s*\n([^#]*?)일주일\s*정도\s*지나면서\s*여드름의?\s*개수가?\s*조금씩?\s*달라지는?\s*흐름이?\s*(나타남|보임|확인됨|관찰됨)\.?/g,
    "### 1주\n$1일주일 정도 지나면서 여드름 양상이 조금씩 달라지기 시작함."
  );
