// ★ countCommercialViolations — BLOCK_MAP 기반 카테고리 카운트
// review 모드는 FIRST_PERSON / REVIEW_TONE 일부를 위반에서 제외
// ============================================================
function countCommercialViolations(text, mode) {
  const counts = {
    EFFECT_WORDS:  0,
    CTA_WORDS:     0,
    REVIEW_TONE:   0,
    FIRST_PERSON:  0,
    PRICE_BAIT:    0,
    CLINIC_PRAISE: 0,
  };
  // review 모드: 1인칭과 후기어투 일부는 정상 — 카운트에서 제외할 카테고리
  const skipCats = (mode === "review")
    ? new Set(["FIRST_PERSON"])  // 1인칭은 review에서 정상
    : new Set();
  for (const [cat, regs] of Object.entries(PAIN_BLOCK_MAP)) {
    if (skipCats.has(cat)) continue;
    for (const r of regs) {
      const m = text.match(r);
      if (m) counts[cat] += m.length;
    }
  }
  counts.total = Object.values(counts).reduce((a, b) => a + b, 0);
  return counts;
}

