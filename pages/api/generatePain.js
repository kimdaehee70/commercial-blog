// ★ 지역 키워드 반복 분산 (4회 초과 시 변형으로 교체)
// ============================================================
function spreadPainRegionKw(text, region) {
  if (!region) return text;
  // ★ region 정규식 특수문자 escape (인수인계 PART 3-2 패턴)
  const escapedRegion = String(region).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const regionKwPattern = new RegExp(escapedRegion + "\\s*통증의학과", "g");
  const matches = text.match(regionKwPattern) || [];
  // ★ v3.1: 임계값 4 → 3 (4번째부터 변형 시작)
  if (matches.length <= 3) return text;

  const variants = ["해당 진료처", "해당 기관", "이 진료처", "해당 의료기관"];
  let count = 0;
  let vIdx = 0;
  // 3회까지는 보존, 4번째부터 변형 (마지막 1회는 변형하지 않음 — 마무리 부분 키워드 보존)
  const limit = matches.length - 1; // 마지막 1개는 그대로 두기
  return text.replace(regionKwPattern, (m) => {
    count++;
    if (count <= 3) return m;
    if (count > limit) return m;
    const v = variants[vIdx % variants.length];
    vIdx++;
    return v;
  });
}

