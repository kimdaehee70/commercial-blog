function injectPainExamValue(text, treatmentId) {
  const ev = PAIN_EXAM_VALUES[treatmentId];
  if (!ev) return text;
  if (/\d+회|\d+샷|\d+ml|\d+유닛/.test(text)) return text;
  const inject =
    "\n\n> 💡 **참고 수치** | " +
    "치료량: " + ev.shot + " | " +
    "간격·횟수: " + ev.session + " | " +
    "회복: " + ev.recovery + " | " +
    "비용: 상담 시 안내" + "\n";
  const idx = text.indexOf("## 상담");
  if (idx !== -1) {
    const after = text.indexOf("\n##", idx + 5);
    if (after !== -1) return text.slice(0, after) + inject + text.slice(after);
  }
  return text + inject;
}

