// INFO_BLOCK 강제 삽입 — 결정 섹션 바로 아래
// ============================================================
function insertPainInfoBlock(text, treatmentId) {
  if (text.includes("비교") && text.includes("vs")) return text;
  const block = PAIN_INFO_BLOCKS[treatmentId];
  if (!block) return text;
  const blockText =
    "\n\n## " + block.title + "\n" +
    block.items.map(i => "- " + i).join("\n") + "\n";

  const decisionIdx = text.indexOf("## 결정");
  if (decisionIdx !== -1) {
    const nextHeaderIdx = text.indexOf("\n##", decisionIdx + 5);
    if (nextHeaderIdx !== -1) {
      return text.slice(0, nextHeaderIdx) + blockText + text.slice(nextHeaderIdx);
    }
  }
  // pain은 "치료 후 변화" 헤더, derma 호환을 위해 양쪽 모두 검색
  let resultIdx = text.lastIndexOf("## 치료 후");
  if (resultIdx === -1) resultIdx = text.lastIndexOf("## 시술 후");
  if (resultIdx !== -1) {
    return text.slice(0, resultIdx) + blockText + text.slice(resultIdx);
  }
  return text + blockText;
}

