// 메인 정제 — mode 분기
// ============================================================
function cleanPainText(text, keyword, mode) {
  const validMode = ["commercial", "personal", "review"].includes(mode) ? mode : "personal";
  let t = text;

  // 백슬래시 이스케이프 정리 (공통)
  t = t
    .replace(/\\n\\n/g, "\n\n")
    .replace(/\\n/g, " ")
    .replace(/\\r/g, "")
    .replace(/\\t/g, " ")
    .replace(/[ \t]{2,}/g, " ")
    .replace(/\n /g, "\n")
    .replace(/ \n/g, "\n");

  // 조사오류 교정 (공통)
  const fixes = [
    [/을를/g, "을"], [/이가/g, "이"], [/은는/g, "은"], [/와과/g, "와"],
    [/으로로/g, "으로"], [/에서서/g, "에서"], [/부터터/g, "부터"], [/까지지/g, "까지"],
    [/에게게/g, "에게"], [/하고고/g, "하고"],
    [/([가-힣])\1{2,}/g, "$1"],
    [/\.{4,}/g, "..."], [/!{2,}/g, "!"], [/\?{2,}/g, "?"],
  ];
  fixes.forEach(([pat, rep]) => { t = t.replace(pat, rep); });

  // 같은 단어 인접 중복 제거
  t = t.replace(/([가-힣]{2,6})\s+\1\s+/g, "$1 ");
  t = t.replace(/([가-힣]{2,6})\s+\1([가-힣]{2,})/g, "$1$2");

  // 키워드 3회↑ 연속 반복 → 축약
  if (keyword) {
    const kw = keyword.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const kwReg = new RegExp("(" + kw + ")[^가-힣a-zA-Z0-9]{0,5}\\1[^가-힣a-zA-Z0-9]{0,5}\\1", "g");
    t = t.replace(kwReg, "$1");
  }

  // ★ mode 분기 — 핵심
  if (validMode === "commercial") {
    t = cleanCommercialPain(t);
  } else if (validMode === "review") {
    t = cleanReviewPain(t);
  } else {
    t = cleanPersonalPain(t);
  }

  // GPT 오타 교정 (공통)
  t = t
    .replace(/지이었(거든요|답니다|어요|네요|군요)/g, "졌$1")
    .replace(/사라지었/g, "사라졌")
    .replace(/생기이었/g, "생겼")
    .replace(/없어지이었/g, "없어졌")
    .replace(/하이었(거든요|답니다|어요|네요|군요|습니다|어|지요)/g, "했$1")
    .replace(/필요하이었/g, "필요했")
    .replace(/필요하었/g, "필요했")
    .replace(/(\S)이었답니다/g, "$1였답니다")
    .replace(/좋었/g, "좋았")
    .replace(/하시었답니다/g, "하셨답니다")
    .replace(/하시었어요/g, "하셨어요");

  return t;
}

