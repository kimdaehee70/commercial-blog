function calcPainCharCount(text) {
  if (!text) return 0;
  return text
    .replace(/\[이미지:[^\]]*\]/g, "")
    .replace(/^HASHTAGS:.+$/gm, "")
    .replace(/^##\s*/gm, "")
    .replace(/\s/g, "").length;
}

function removeDuplicateSentences(text) {
  const seenHeaders = new Set();
  const lines = text.split("\n");
  const deduped = [];
  let skip = false;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const isHeader = /^#{1,3}\s/.test(line);
    if (isHeader) {
      const headerKey = line.trim().replace(/^#+\s*/, "").slice(0, 15);
      if (seenHeaders.has(headerKey)) { skip = true; continue; }
      seenHeaders.add(headerKey);
      skip = false;
    }
    if (!skip) deduped.push(line);
  }
  const dedupedText = deduped.join("\n");

  const seenParas = new Set();
  const result = dedupedText.split(/\n{2,}/).filter(para => {
    const key = para.replace(/\s/g, "").slice(0, 30);
    if (!key || seenParas.has(key)) return false;
    seenParas.add(key);
    return true;
  }).join("\n\n");

  const seenSents = new Set();
  return result.split(/(?<=[.!?。])\s+/).filter(s => {
    const key = s.replace(/\s/g, "").slice(0, 20);
    if (!key || seenSents.has(key)) return false;
    seenSents.add(key);
    return true;
  }).join(" ");
}

