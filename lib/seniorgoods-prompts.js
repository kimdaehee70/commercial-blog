// buildPrompt: 품목(treatment)·지역·DIRECTION을 받아 본문 생성 지시 구성
export function buildPrompt({ treatment, region, storeName = "{storeName}" }) {
  const dir = treatment?.DIRECTION || {};
  return `
[업종] 노인용품 전문점
[지역] ${region}
[주제] ${treatment?.name || ""}
[화자] ${region} 노인용품 전문점 (기관/전문점 화자, 상담사 톤 — 전문점명/이름 자리 없이 "${region} 노인용품 전문점"으로만 칭한다)

[이 글이 답해야 할 보호자 고민]
${dir.concern || ""}

[안내 방향]
${dir.effect || ""}

[도입 훅 예시]
${dir.hook || ""}

[핵심 키워드] ${dir.keyword || treatment?.name || ""}

[작성 지침 — 7단계 본문 구조]
1. 인사: 반드시 "안녕하세요. ${region} 노인용품 전문점입니다."로 시작한 뒤, 보호자의 고민에 공감한다. 첫 문장에 전문점명/이름 자리를 넣지 않는다.
2. 제품이 필요한 상황: 어떤 상황에서 이 제품을 찾게 되는지 정보로 안내.
3. 제품 특징: 제품의 기능·종류 차이를 정보 중심으로 설명(과장·효과보장 금지).
4. 사용 대상: 어떤 어르신에게 적합한지 안내.
5. 선택 시 확인사항: 고를 때 점검할 기준을 안내.
6. 관리방법: 사용 후 관리·점검 방법 안내.
6-1. [이용 흐름] 전문점에서 제품을 이용하는 실제 과정을 짧은 한 단락으로 자연스럽게 보여준다. 예: 상담 → 어르신 체형·이동 환경 확인 → 적합한 품목 함께 선택 → 사용 방법·관리 방법 안내(복지용구 급여 대상이면 급여확인서 확인). 목록·번호 없이 서술형 3~4문장으로, 보호자가 이용 과정을 그릴 수 있게 쓴다(제품 나열이 아닌 이용 과정 중심).
7. 마무리: 글 전체 재요약 금지. 상담/문의 안내로 짧게 닫는다.
- 정보블럭을 글 흐름에 자연스럽게 배치.
- 가격·구매 유도 금지, 보험·비용 언급 시 단정 금지("상담 시 안내" 톤).
`.trim();
}

// 화자 오염 가드 (storeName이 화자/끝서명 오염 방지)
export function buildOfficeIntro({ region, storeName }) {
  const safe = (storeName || "").trim();
  // 기관/전문점 화자 키워드가 없으면 일반 안내문으로 대체
  const isInstitution = /노인용품|복지용품|전문점|복지/.test(safe);
  if (!safe || !isInstitution) {
    return `안녕하세요. ${region} 노인용품 전문점입니다.`;
  }
  return `안녕하세요. ${region} ${safe}입니다.`;
}

// 끝 닉네임/서명 제거 정규식 (closing 오염 차단)
export function stripOwnerSignature(text) {
  return text
    .replace(/[-–—·]\s*[가-힣A-Za-z0-9_]{2,20}\s*드림\s*$/g, "")
    .replace(/작성자\s*[:：].*$/gm, "")
    .trim();
}

