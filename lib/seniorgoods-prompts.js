// 정보블럭 렌더 헬퍼 (generateSeniorgoods.js insertInfoBlock에서 사용)
export function renderInfoBlocks() {
  return Object.values(SENIORGOODS_INFO_BLOCKS)
    .map((b) => `■ ${b.title}\n${b.items.map((i) => `· ${i}`).join("\n")}`)
    .join("\n\n");
}
