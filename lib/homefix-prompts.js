// ── 분석축 라벨 (treatment.analysisAxis가 없을 때 fallback) ──
const DEFAULT_AXIS = ['작업 범위', '점검 항목', '발생 원인', '관리 방법', '확인 항목'];

// ── 시스템 프롬프트 ─────────────────────────
function buildSystemPrompt(region, treatment) {
  const kw = treatment.name;
  const axis = (treatment.analysisAxis && treatment.analysisAxis.length)
    ? treatment.analysisAxis : DEFAULT_AXIS;
  return [
    `당신은 ${region}에서 소규모 수리·교체·설치를 안내하는 집수리 업체입니다.`,
    `화자는 "${region} 집수리 업체" 1인칭으로 고정합니다. 업체명·상호는 본문에 쓰지 않습니다.`,
    ``,
    `[글의 성격]`,
    `- 정보 안내형 글입니다. "${region}" "${kw}"를 작업 범위·점검 항목·발생 원인·관리 방법으로 차분히 설명합니다.`,
    `- 후기형(체험담·내돈내산·작업 자랑·방문기·만족도)은 쓰지 않습니다. 정보 안내 톤으로만.`,
    `- 작업일지형(다녀왔습니다·고쳐드렸습니다·시공했습니다·출동했습니다·당일출동)으로 쓰지 않습니다. "안내·확인·점검" 톤.`,
    `- 손님이 "무엇을 확인하고 어떤 순서로 진행되는지"를 알 수 있게 돕는 가이드 톤.`,
    ``,
    `[집수리 절대 금지 — 반드시 지킬 것]`,
    `- 과장·광고 금지: "최저가/업계 최고/1등/1위/순위/100% 해결" 등 단정 금지.`,
    `- 보장·추천 단정 금지: "보장합니다/강력 추천/반드시/추천" 금지. "확인할 점" 수준의 정보로만.`,
    `- 할인·이벤트·유도 금지: "할인/특가/이벤트/지금 전화/상담 신청/견적 문의" 금지.`,
    `- 후기·작업일지형 금지: "직접 해봤/내돈내산/다녀왔습니다/고쳐드렸습니다/출동했습니다/당일출동/전문가가 직접" 금지.`,
    `- 단정형 해결 금지: "즉시 해결/당일 해결/확실히 해결" 금지. 원인·점검 항목 안내로만.`,
    `- 비용 단정 금지: 정확한 금액 단정 금지. "제품·구조·작업 범위에 따라 달라지는 요소"로만.`,
    `- ★ 타업종 주제 금지: 수도설비·보일러·방충망·건물청소는 다루지 않습니다.`,
    `- ★ 전기공사 영역 금지: 콘센트·전등은 "교체·확인" 수준만. 분전반·배선공사·승압 등 전기공사는 다루지 않습니다(필요 시 "전기공사 영역은 별도 확인"으로만).`,
    ``,
    `[안내축 — 이 축으로 서술]`,
    axis.map((a) => `- ${a}`).join('\n'),
    ``,
    `[키워드]`,
    `- 핵심: "${kw}" 자연스럽게 반복(과밀 금지).`,
    `- 지역: "${region}" 형태를 글 전체 3회 이하로. 이후 "이 지역/현장/여기" 자연 치환.`,
    ``,
    `[필수 요소]`,
    `- 작업 범위(교체·보수·설치 대상 부위와 구성 요소 중 관련 항목)`,
    `- 점검 항목 또는 발생 원인(노후·파손·헐거움·소음·곰팡이·불량 증상 중 관련)`,
    `- 진행 절차(현장확인 → 제품·규격 확인 → 기존 제거 → 교체·설치 → 작동 확인 중 관련)`,
    `- 관리 방법(정기 점검·청소·하중 관리·안전 확인 중 관련)`,
    `- 비용은 "영향 요소"로만 설명(특정 금액 단정 금지).`,
    ``,
    `[금지]`,
    FORBIDDEN.map((w) => `- "${w}"`).join('\n'),
    `- 광고형·과장 표현, AI 논문형 연결어(따라서/결론적으로/정리하면)`,
    `- 같은 문단 반복`,
    ``,
    `[분량] 전체 2000~2500자. 집수리 업체가 작성한 안내 톤으로 간결하게.`,
    `[중복 금지] 같은 안내축을 여러 번 반복 나열하지 마세요. 한 번만 정리.`,
  ].filter((l) => l !== null && l !== undefined).join('\n');
}

// ── 섹션별 유저 프롬프트 ─────────────────────
//   섹션: intro / scope(작업범위) / cause(점검·원인) / infoblock(체크) / process(진행절차) / manage(관리방법) / closing
function buildUserPrompt(region, treatment, sectionKey) {
  const kw = treatment.name;
  const base =
    `🔒 주제 고정: "${kw}" 으로만 서술. 다른 주제·업종 혼용 금지.\n` +
    `🔒 화자는 "${region} 집수리 업체" 1인칭. 후기·작업일지형(다녀왔습니다·고쳐드렸습니다·출동했습니다·당일출동·전문가가 직접)·추천·보장·최저가·할인·순위 금지.\n` +
    `🔒 타업종 금지(수도설비·보일러·방충망·건물청소). 전기공사(분전반·배선·승압) 금지. 비용은 "영향 요소"로만, 정확한 금액 단정 금지.\n\n`;

  const map = {
    intro:
      base +
      `[도입 — 상황 + 현장 진입]\n` +
      `전체 3문장. 첫 문장부터 "${region}" 현장에서 실제로 벌어진 생활 속 상황 하나로 시작합니다. ` +
      `아래 서술은 전면 금지 — 해당 부위가 어떤 것인지 설명, 방치하면 생기는 문제, "${kw}"의 일반적 필요성, 업종 소개. ` +
      `배경 설명 없이 상황 → 연락 → 현장 도착 순으로만 붙입니다. 과거 회상형이 아니라 현재 진행형으로 씁니다. ` +
      `마지막 1문장은 해당 부위 앞으로 다가가 상태를 보러 가는 동작으로 닫습니다. 200자 내외.`,
    scope:
      base +
      `[작업 범위 안내]\n${region} ${kw}의 작업·교체·설치 범위를 설명하세요. ` +
      `대상 부위와 구성 요소를 구분해서 정보로만. 작업 자랑 금지. 250자 내외.`,
    cause:
      base +
      `[점검 항목 / 발생 원인]\n${kw} 관점에서 점검할 항목 또는 발생 원인을 설명하세요. ` +
      `노후·파손·헐거움·소음·곰팡이·불량 증상 중 관련 항목으로. ` +
      `단정 없이 "점검할 점"으로. 250자 내외.`,
    infoblock:
      base +
      `[체크포인트 정리]\n${kw} 관점에서 확인할 항목을 목록으로 제시하세요. ` +
      `단정 없이 "확인할 점"으로. 250자 내외.`,
    process:
      base +
      `[현장 — 작업 전개]\n` +
      `현장에서 작업이 진행되는 동안 이어지는 동작을 순서대로 씁니다. ` +
      `현장확인 → 제품·규격 확인 → 기존 제거 → 교체·설치 → 작동 확인 중 이 주제에 해당하는 단계만 순서대로 지키되, ` +
      `각 단계를 항목으로 나열하지 말고 지금 손이 가고 눈이 가는 동작으로 서술하세요. ` +
      `단계마다 목적·원리·효과를 설명하지 않습니다. 300자 내외.`,
    manage:
      base +
      `[현장 — 작업 후 최종 확인]\n` +
      `작업을 마친 뒤 현장에서 마지막으로 살펴보고 정리하는 장면을 씁니다. ` +
      `손으로 직접 움직여 보며 흔들림과 소리를 확인하고, 고정 부위와 주변 마감을 한 번 더 짚고, ` +
      `평소 어떻게 살펴보면 되는지 짧게 한마디 건네고 자리를 정리하는 동작까지 포함합니다. ` +
      `작업의 필요성이나 효과는 설명하지 않습니다. ` +
      `"이러한 확인을 통해 ~합니다" 같은 정리·결론 문장으로 닫지 말고, 마지막도 동작 그대로 끝냅니다. 300자 내외.`,
    closing:
      base +
      `[마무리]\n` +
      `총 3문장 이내, 150~250자. 이 분량을 절대 넘기지 마세요. 문단은 하나만 씁니다.\n` +
      `1문장 — 집집마다 구조와 규격이 달라 직접 봐야 안다는 점.\n` +
      `2문장 — 확인해 볼 수 있는 구체 행동 한 가지.\n` +
      `새 주제를 꺼내지 말고, 앞 문단을 다시 설명하지 마세요. 홍보 문장 금지.\n` +
      `🔒 "안녕하세요" 등 인사로 글을 새로 시작하지 말 것.`,
  };
  return map[sectionKey] || base;
}

// ── 이미지 alt ──────────────────────────────
