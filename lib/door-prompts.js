//   안전 차단(스프링 장력·전원) 지시는 SCENE work 에 해당 토큰이 있는 cat 에만 건다.
//   [세션64] 전 cat 무조건 지시 → standard 11cat(전기 무관)에서 '전기를 차단합니다' 창작.
//   동일 원인으로 intro 예시의 현관문 전용 증상('손잡이를 올려야 잠김')이 붙박이장·포켓도어로 누수.
