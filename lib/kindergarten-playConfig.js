/**
 * getSectionInstruction(subKw, sectionKey, flowBlock)
 * → 프로그램별 reaction/episode instruction 반환
 * → generate.js handler SECTIONS에서 호출
 */
export function getSectionInstruction(subKw, sectionKey, flowBlock) {
  subKw = subKw?.trim().replace(/\s+/g, "").toLowerCase();
  const exactKey = Object.keys(SECTION_INSTRUCTIONS).find(k => k.toLowerCase() === subKw);
  const partialKey = Object.entries(KEY_MAP)
    .sort((a, b) => b[0].length - a[0].length)
    .find(([k]) => subKw?.includes(k.toLowerCase()))?.[1];
  const resolved = exactKey || partialKey;
  if (!resolved) {
    throw new Error(`SECTION 매칭 실패: "${subKw}" — SECTION_INSTRUCTIONS 또는 KEY_MAP에 키워드 추가 필요`);
  }

  if (!SECTION_INSTRUCTIONS[resolved]) {
    throw new Error(`프로그램 instruction 없음: ${resolved}`);
  }
  if (!SECTION_INSTRUCTIONS[resolved][sectionKey]) {
    throw new Error(`SECTION 키 오류: ${sectionKey}`);
  }
  const inst = SECTION_INSTRUCTIONS[resolved][sectionKey];

  // flowBlock을 항상 뒤에 붙임
  return `${inst}\n${flowBlock}`.trim();
}
