/**
 * getFlowSlice(flow, section)
 * → 섹션이 담당할 flow steps 반환
 *
 * 분배 기준:
 *   intro     → [0]          첫 단계 (입장/도입)
 *   reaction  → [0, 1]       1~2단계 (첫 반응)
 *   classroom → 전체          코너 기준이라 전체 참고
 *   operation → 전체          교사 역할 전체
 *   episode   → [중간~끝-1]  핵심 체험 단계
 *   closing   → [끝]         마지막 단계
 */
export function getFlowSlice(flow, section) {
  if (!flow?.length) return [];
  const len = flow.length;

  switch (section) {
    case "intro":
      return flow.slice(0, 1);                          // flow[0]
    case "reaction":
      return flow.slice(0, Math.min(2, len));           // flow[0~1]
    case "classroom":
      return flow;                                       // 전체 (코너 매핑)
    case "operation":
      return flow;                                       // 전체 (교사 기준)
    case "episode": {
      const mid  = Math.max(1, Math.floor(len / 2));
      const end  = Math.max(mid + 1, len - 1);
      return flow.slice(mid, end);                      // 중반 핵심 단계
    }
    case "closing":
      return flow.slice(-1);                            // 마지막 단계
    default:
      return flow;
  }
}

/**
 * buildFlowBlockForSection(flow, section)
 * → 섹션에 맞는 flow steps만 뽑아서 프롬프트 블록 생성
 * → generate.js에서 이걸 쓰면 flowIndex 공유 완성
 */
export function buildFlowBlockForSection(flow, section) {
  const steps = getFlowSlice(flow, section);
  return buildFlowBlock(steps);
}

