// ============================================================
// ★ [신규] 국물 프레임 회피 가드 — class별 국물 어휘 허용/금지 슬롯
//   directionGuide에 1줄로 주입. 모든 섹션 common에 전파됨.
//   soup = 허용 / meat·rice·noodle = 금지 (한식 v2.5 이연분 선반영).
// ============================================================
const SOUP_FRAME_WORDS = '국물·육수·우려낸·뚝배기·말아·탕·국물에 밥·국물 농도·진한 국물·국물 양';
function getSoupFrameGuard(menu) {
  const cls = SNACK_TITLE_MENU_CLASS[menu] || 'meat';
  if (cls === 'soup') {
    return `
[국물 프레임 — 허용 (${menu} = soup 결)]
- 이 메뉴는 국물 요리. 국물·육수 묘사 자연스럽게 사용 가능.
- 단, "국물에 밥 말아" 등 밥 메뉴 전용 표현은 과하지 않게.`;
  }
  // meat / rice / noodle → 국물 어휘 전면 금지
  const axisHint = cls === 'noodle'
    ? '비빔·면식감·양념이 면에 밴 정도'
    : cls === 'rice'
    ? '속재료 구성·밥과 김의 식감'
    : '양념·졸임·바삭함·튀김옷';
  return `
[국물 프레임 — 금지 ★★ (${menu} = ${cls} 결, 인수인계 분식설계확정)]
- 이 메뉴는 국물 요리가 아님. 다음 어휘 절대 사용 금지: ${SOUP_FRAME_WORDS}
- ❌ "국물의 농도/양", "진한 국물", "국물이 적다면", "국물에 밥을 말아"
- ❌ "국물을 떠서", "육수가", "뚝배기" → 이 메뉴엔 등장 불가
- ✅ 대체 축: ${axisHint} 중심으로 서술
- 곁들임으로 국·찌개를 언급할 때도 이 메뉴 자체를 국물 요리로 묘사하지 말 것`;
}

// ============================================================
// 0. DIRECTION 헬퍼 — 데이터 조합으로 동적 생성
// ============================================================
export function getSnackDirection(treatment, situation, purpose) {
  if (!treatment) {
    return buildDirection({ menu: '', situation, purpose });
  }
  const menu = treatment.menu || treatment.menuRef || '';
  return buildDirection({ menu, situation, purpose });
}

