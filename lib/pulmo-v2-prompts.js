// ★★ 4섹션 — decisionAxis 분기 (프롬프트는 단일 함수, 축만 교체)
function _decision(t, region) {
  const d = getDirection(t.id);
  const isExam = d.decisionAxis === "exam";
  const compare = t.compareWith || "다른 방법";

  const axisGuide = isExam
    ? (
      "[축: 검사형 — 어떤 검사를 선택하는가]\n" +
      "- 어떤 경우에 이 검사가 선택되는지를 기준 자체로 설명합니다.\n" +
      "- 이 검사로 무엇을 확인하는지, 다른 방법(" + compare + ")과 확인 범위가 어떻게 다른지를 서술.\n" +
      "- 결과에 따라 다음 진료·처치가 어떻게 이어지는지를 흐름으로 한 문장 포함.\n" +
      "- 우열 단정 금지. '더 좋은 검사'가 아니라 '확인하려는 대상이 다르다'는 관점 유지.\n" +
      "- 연령·검사 주기 단정 금지. '증상·흡연력·위험 요인·이전 검사 결과를 종합해 검토됩니다' 형태로만.\n" +
      "- 치료 방법 설명 금지. 이 섹션은 '검사 선택'에 대한 글입니다.\n"
    )
    : (
      "[축: 질환형 — 검사·치료가 결정되는 기준]\n" +
      "- 원인 확인 → 필요한 검사 → 약물 접근 → 관리·경과 확인 → (해당 시) 다른 진료과와의 논의 순으로 기준을 설명합니다.\n" +
      "- '어떤 상황에서 어느 단계가 검토되는지'가 핵심이며, 단계별 방법의 상세 설명이 아닙니다.\n" +
      "- 흉부외과적 수술은 '다른 진료과와 함께 논의되는 방향' 수준으로만 스칩니다. 수술 방법·절개·마취 과정 설명 금지.\n" +
      "- " + compare + " 와의 구분이 판단에 관여한다면 '무엇을 기준으로 나뉘는지' 관점에서만 짧게.\n" +
      "- 효과 보장·완치 단정 금지. 개인 결정 서사('~하기로 했다') 금지.\n"
    );

  return (
    "[섹션: 검사·치료는 어떤 기준으로 결정되나요? | 180~260자] ★ 이 글의 핵심 축\n" +
    "주제: " + t.name + " | 비교: " + compare + "\n" +
    "🔒 결정 기준: " + d.decisionRule + "\n\n" +
    axisGuide +
    "※ 이 섹션에 한해 다른 방법과의 확인 범위 비교가 허용됩니다(우열 아닌 '대상이 다르다' 관점).\n" +
    aiSmell()
  );
}

