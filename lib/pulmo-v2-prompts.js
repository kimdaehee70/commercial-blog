export function buildPulmoV2Prompt(section, treatment, region) {
  switch (section) {
    case "concern":           return _concern(treatment, region);
    case "visitTrigger":      return _visitTrigger(treatment, region);
    case "examination":       return _examination(treatment, region);
    case "treatmentDecision": return _decision(treatment, region);   // ★ decisionAxis 분기
    case "checkPoint":        return _checkPoint(treatment, region);
    case "sceneVisit":        return _scene(treatment, region);
    case "closing":           return _closing(treatment, region);
    default:                  return "";
  }
}

function _concern(t, region) {
  const d = getDirection(t.id);
  return (
    "[섹션: 지금 이런 상황인가요? | 120~180자]\n" +
    "⚠ 소제목(##)을 출력하지 말고 본문부터 바로 시작합니다. [세션40][NOHDR-01]\n" +
    "주제: " + t.name + " | 지역: " + region + "\n" +
    "🔒 검색 직전 상황: " + d.concern + "\n" +
    "🔒 생활 장면: " + d.hook + "\n\n" +
    "[작성 방향]\n" +
    "- 이 주제를 찾아본 사람이 지금 어떤 상황에 있는지를 일반 정보로 짚어줍니다.\n" +
    "- 특정 인물 사연('한 사람은 ~했다') 금지. 1인칭 후기 금지.\n" +
    "- 진료명·검사명을 앞세우지 말고 겪고 있는 증상·상황 중심으로 서술.\n" +
    "- 불안을 키우는 표현 금지. 확인이 필요할 수 있다는 정도의 중립 톤.\n" +
    aiSmell()
  );
}

