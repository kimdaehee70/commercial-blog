function getDirection(treatmentId) {
  return EYE_DIRECTION[treatmentId] || {
    concern: "눈 건강이 점점 나빠지는 것 같아서",
    effect:  "시력·눈 건강 개선",
    hook:    "거울을 보다가 눈 상태가 신경 쓰였을 때",
    keyword: "안과 진료",
  };
}

export function getEyeImageAlts(treatment, region, activeKeyword) {
  const name       = treatment.name;
  const dir        = getDirection(treatment.id);
  const ak         = activeKeyword || name;
  const akClean    = ak.replace(/\s/g, "");
  const fullKw     = region + " " + ak;
  const eff0       = (dir.effect.split(",")[0] || "").trim();
  const eff1       = (dir.effect.split(",")[1] || dir.effect.split(",")[0] || "").trim();
  const eff2       = (dir.effect.split(",")[2] || dir.effect.split(",")[1] || dir.effect.split(",")[0] || "").trim();

  return {
    concern:  "[이미지: " + fullKw + " 후기 " + dir.concern.replace("서", "").replace("져서", "").trim() + " 고민 | " + ak + " 시작 전 상태]",
    search:   "[이미지: " + region + " 안과 " + ak + " 검색 | " + fullKw + " 후기 비교 화면]",
    consult:  "[이미지: " + region + " 안과 " + ak + " 상담 과정 | " + fullKw + " 상담 장면]",
    decision: "[이미지: " + fullKw + " 결정 | " + region + " 안과 " + ak + " 선택 이유]",
    result0:  "[이미지: " + fullKw + " 1일차 후기 | " + ak + " 직후 상태]",
    result1:  "[이미지: " + ak + " 1주 변화 후기 | " + eff0 + " 초기 변화]",
    result2:  "[이미지: " + fullKw + " 2주 변화 | " + eff1 + " 중간 변화]",
    result3:  "[이미지: " + fullKw + " 1개월 변화 후기 | " + region + " 안과 " + akClean + " 최종 결과]",
    summary:  "[이미지: " + fullKw + " 후기 마무리 | " + eff2 + " 일상 변화]",
    closing:  "[이미지: " + fullKw + " 후기 최종 결과 | 진료 후 달라진 모습]",
  };
}

