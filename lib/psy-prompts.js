// getImageAlts — 섹션별 [이미지: ...] 박스 alt
// 🔒 v2 (2026.05): 피부과 방식 — 섹션별 분리 + change는 1주/2주/1개월 3박스
//   네이버 블로그 붙여넣기 시 자주색 사진 자리 표시 박스로 렌더링됨
// ─────────────────────────────────────────────────────────────
export function getImageAlts(treatmentName, region, activeKeyword) {
  const ak = activeKeyword || treatmentName;
  // '진료'로 끝나는 키워드의 경우 뒤에 '진료'가 또 붙는 것 방지
  const akBase = ak.replace(/\s*진료\s*$/, '');
  const akClean = ak.replace(/\s/g, '');
  const fullKw = `${region} ${ak}`;
  return {
    intro:    `[이미지: ${fullKw} 후기 고민 시작 시점 | ${akBase} 진료 전 일상]`,
    search:   `[이미지: ${region} 정신건강의학과 ${ak} 검색 | 후기 비교 화면]`,
    consult:  `[이미지: ${region} 정신건강의학과 ${ak} 첫 방문 | 상담 장면]`,
    decision: `[이미지: ${region} 정신건강의학과 ${ak} 결정 | 치료 방향 정리]`,
    change1:  `[이미지: ${akBase} 1주 변화 후기 | ${region} 정신건강의학과 ${akClean} 초기 적응]`,
    change2:  `[이미지: ${fullKw} 2주 변화 | ${region} 정신건강의학과 ${akClean} 중간 경과]`,
    change3:  `[이미지: ${fullKw} 1개월 변화 후기 | ${region} 정신건강의학과 ${akClean} 회복 흐름]`,
    closing:  `[이미지: ${fullKw} 후기 현재 상태 | 진료 후 일상 회복]`,
  };
}

