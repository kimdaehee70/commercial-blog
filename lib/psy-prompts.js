// ─────────────────────────────────────────────────────────────
// buildPrompt — 섹션별 사용자 프롬프트
// ─────────────────────────────────────────────────────────────
export function buildPrompt({
  sectionKey,
  region,
  treatmentId,
  treatmentName,
  activeKeyword,
  fullKeyword,
  writtenSections,
}) {
  const dir = DIRECTION[treatmentId] || {};
  const concern = dir.concern || `${treatmentName} 관련 어려움이 길게 이어져서`;
  const effect  = dir.effect  || `증상 안정, 일상 회복`;
  const hook    = dir.hook    || `${treatmentName}을(를) 알아봐야겠다고 생각한 어느 날`;
  const keyword = dir.keyword || treatmentName;

  // 공통 가드 — 모든 섹션에 주입
  const COMMON_GUARD = `
🔒 집중 키워드: "${activeKeyword}" 으로만 서술. 다른 진료 혼용 금지.
🔒 복합 키워드 필수: "${fullKeyword}" 1~2회 자연스럽게 포함.
🔒 정신과 절대 금지: 약물명·진단코드·자살관련표현·효과보장표현 일체 사용 금지.
🔒 카톡 톤: 짧은 문장, 친구에게 말하듯, 직접 진술 위주.`;

  // 이미 쓴 섹션 안내
  const writtenInfo = writtenSections.size > 0
    ? `\n[이미 작성된 섹션]: ${[...writtenSections].join(', ')} — 이 섹션들과 같은 문장·문단 반복 금지.\n`
    : '';

  switch (sectionKey) {
    case 'intro':
      return `[섹션: 고민]
역할: 진료를 받게 된 일상 속 구체 장면 묘사. 감정·결심 표현은 금지하고 사실적 묘사만.
최소 350자.
${COMMON_GUARD}

지역: ${region}
진료: ${treatmentName} (집중 키워드: ${keyword})
고민 방향: ${concern}
첫 문장 후킹 예시: ${hook}

[작성 지침]
- 첫 2문장은 짧고 강하게. 줄을 끊어서 시작.
- 직장/가족/일상 중 구체 장면 1개 (출근길, 회의 중, 아이 재우는 시간 등)
- "결심하게 됐어요" 같은 결심 표현 절대 금지
- "${keyword}" 단어 1~2회 자연스럽게 등장
- 마지막 문장에서 "알아봐야겠다" 정도까지만 (방문 결정은 다음 섹션)
- 🔒 모든 문장은 정확한 어법으로 마침표 종결. "필요할 알아봐야겠다" 같은 비문 금지
  → "${keyword} 관련 진료가 필요한지 알아봐야겠다" 형태로 정확하게
${writtenInfo}`;

    case 'search':
      return `[섹션: 탐색]
역할: ${region} 지역에서 ${treatmentName} 진료를 받을 곳을 알아본 과정. 사실 진술 위주.
최소 350자.
${COMMON_GUARD}

[작성 지침]
- "신뢰가 갔어요/믿음이 갔어요/인상적이었어요" 같은 감정 결론 금지
- "후기가 좋아서/유명한 병원이라서" 같은 모호한 평가 금지
- 대신 사실만: 진료 시간 길이, 상담 병행 여부, 접근성, 비급여 항목 안내 여부
- 비교 기준 2~3개를 짧게 나열 (예: 진료 시간 / 상담 병행 / 보험 처리)
- "${fullKeyword}" 1회 등장
${writtenInfo}`;

    case 'consult':
      return `[섹션: 첫 방문]
역할: 첫 진료일에 실제로 일어난 일. 시간 순서로 사실 진술.
최소 380자.
${COMMON_GUARD}

[작성 지침]
- 접수 → 자가 보고 척도 작성 → 진료실 입장 → 상담 → 진료 결정 순서
- 원장님 말은 직접 진술로: "~라고 설명해 주셨어요" 형태
- 수치 1개 이상: 진료 시간(분), 비용(만원), 척도 점수 중 하나
- "친절하셨어요/따뜻했어요" 같은 감정 평가 금지
- 진료실 분위기는 "조명/자리 배치/소요 시간" 같은 사실로만
- 🔒 마지막 문장은 반드시 명확하게 종결 ("~었어요." / "~더라고요." / "~네요.")
  → "향후 치료 방향에 대해예요" 같은 미완 표현 금지
  → 대신: "향후 치료 방향을 안내받았어요." / "치료 방향에 대한 설명을 들었어요."
${writtenInfo}`;

    case 'decision':
      return `[섹션: 진료 결정]
역할: 어떤 진료 방향으로 결정했는지 + 그 근거. 단정 표현 금지.
최소 360자.
${COMMON_GUARD}

[작성 지침]
- 결정 옵션 2가지 비교 (예: 약물치료 vs 비약물, 단기 vs 장기)
- "${keyword}" 진료를 선택한 이유 2~3개를 사실 기반으로
- "사람마다 다르겠지만, 제 경우에는" 톤 유지
- "확실히 좋아질 거예요" 같은 단정 금지
- 의료광고법: "최고의/유일한" 같은 우월성 표현 금지
${writtenInfo}`;

    case 'change':
      return `[섹션: 진료 후 변화]
역할: 시간 흐름에 따른 본인 변화를 사실 보고.
최소 420자.
${COMMON_GUARD}

[작성 지침]
- 헤더 4개 순서 고정: ### 1주 / ### 2주 / ### 1개월 / ### 2개월
- 🔒 각 헤더 아래 본문은 최소 60자 + 2문장 이상
- 🔒 각 헤더 아래 마지막 문장은 반드시 "~어요." "~네요." "~더라고요." 처럼 마침표로 종결
- 🔒 "줄어들고", "나아지고", "회복되고" 같은 연결어미로 단락 끝내기 금지
  → 반드시 "줄어들고 있어요.", "나아지고 있어요." 형태로 종결
- 변화 표현은 "체감했어요/잡혀가요/관리되고 있어요" 류
- "사라졌어요/완치됐어요/100%" 류 효과 보장 표현 금지
- 🔒 "확실히 잡혀가요/확실히 좋아졌어요/확실히 줄어들었어요" 같은 직설 단정 금지
  → 대신 "점차 잡혀가고 있어요", "조금씩 좋아지고 있어요" 처럼 점진적 표현
- 일상 회복은 "출근길/식사/수면" 같은 구체 영역으로
- 부작용·어려움도 1개 이상 솔직하게 언급 (예: "처음엔 적응 시간이 필요했어요")
${writtenInfo}`;

    case 'closing':
      return `[섹션: 마무리]
역할: 사실 보고 + 본인 현재 상태. 격언·CTA·미래 단정 금지.
최소 280자.
${COMMON_GUARD}

[작성 지침]
- "회복될 거예요/좋아질 거예요" 같은 미래 단정 금지
- "비슷한 분이라면 추천드려요" 같은 CTA 금지
- "${fullKeyword}" 1회 자연스럽게 마무리에 포함
- 마지막 문장은 본인 현재 상태로 담담하게 (예: "지금은 ~하게 지내고 있어요")
${writtenInfo}`;

    default:
      return `[섹션: ${sectionKey}]\n자연스럽게 이어 작성해주세요.\n${COMMON_GUARD}`;
  }
}

