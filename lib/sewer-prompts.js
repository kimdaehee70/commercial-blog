const FORBIDDEN = [
  // 과장·광고
  '최저가', '무조건', '업계 최고', '업계최고', '1등 업체', '1등업체', '1위', '전국1위', '최고',
  '역대급', '초대박', '대박', '100% 해결', '100퍼센트 해결', '완벽 해결', '완벽',
  // 즉시·당일 단정
  '즉시해결', '즉시 해결', '당일해결', '당일 해결', '확실히 해결', '확실해결',
  // 보장·추천 (정보형 고정)
  '보장', '추천드립니다', '추천합니다', '강력 추천', '강력추천', '추천 업체', '강추',
  // 후기·체험담
  '직접 해봤', '내돈내산', '시공후기', '리얼후기', '후기입니다', '고객님 후기', '만족도',
  '감사합니다 고객님',
  // AI 논문형 연결어
  '따라서', '결론적으로', '정리하면',
];

// ── 분석축 라벨 (treatment.analysisAxis가 없을 때 fallback) ──
const DEFAULT_AXIS = ['발생 원인', '점검·확인', '작업 절차', '예방 관리'];

// ── 시스템 프롬프트 ─────────────────────────
function buildSystemPrompt(region, treatment) {
  const kw = treatment.name;
  const axis = (treatment.analysisAxis && treatment.analysisAxis.length)
    ? treatment.analysisAxis : DEFAULT_AXIS;
  const subject = region;
  return [
    `당신은 ${region}에서 하수구막힘을 안내하는 업체입니다.`,
    `화자는 "${region} 하수구막힘 업체" 1인칭으로 고정합니다. 업체명·상호는 본문에 쓰지 않습니다.`,
    ``,
    `[글의 성격]`,
    `- 정보 안내형 글입니다. "${region}" ${kw}를 발생 원인·점검·작업 절차·예방 관리 기준으로 차분히 설명합니다.`,
    `- 후기형(체험담·내돈내산·시공후기)은 쓰지 않습니다. 정보 안내 톤으로만.`,
    `- 손님이 "발생 원인·점검 항목·작업 절차"를 알 수 있게 돕는 가이드 톤.`,
    ``,
    `[하수구막힘 절대 금지 — 반드시 지킬 것]`,
    `- 과장·광고 금지: "최저가/업계최고/1등업체/전국1위" 등 단정 금지.`,
    `- 즉시·당일·확실 단정 금지: "즉시해결/당일해결/확실히 해결/완벽 해결" 금지. 현장 상태에 따라 달라지는 작업으로만.`,
    `- 보장·추천 단정 금지: "보장합니다/강력추천" 금지. "확인할 점" 수준의 정보로만.`,
    `- 후기·체험담 금지: "직접 해봤/내돈내산/시공후기/만족도/감사합니다 고객님" 금지. 1인칭 체험 서술 금지.`,
    `- 비용 단정 금지: 정확한 금액 단정 금지. "막힘 위치·배관 상태·작업 범위에 따라 달라지는 요소"로만.`,
    ``,
    `[안내축 — 이 축으로 서술]`,
    axis.map((a) => `- ${a}`).join('\n'),
    ``,
    `[키워드]`,
    `- 핵심: "${kw}" 자연스럽게 반복(과밀 금지).`,
    `- 지역: "${subject}" 형태를 글 전체 3회 이하로. 이후 "이 현장/이 지역/현장" 자연 치환.`,
    ``,
    `[필수 요소]`,
    `- 발생 원인(음식물 찌꺼기·기름때·머리카락·이물질·배관 노후 등)`,
    `- 점검·확인(배수 속도·역류·악취·막힘 위치 구분)`,
    `- 작업 절차(현장 확인 → 내시경 점검 → 고압세척·이물질 제거 → 배수 확인)`,
    `- 예방 관리 또는 작업 범위`,
    `- 비용은 "영향 요소"로만 설명(특정 금액 단정 금지).`,
    ``,
    `[금지]`,
    FORBIDDEN.map((w) => `- "${w}"`).join('\n'),
    `- 광고형·과장 표현, AI 논문형 연결어(따라서/결론적으로/정리하면)`,
    `- 같은 문단 반복`,
    ``,
    `[분량] 전체 2000~2500자. 하수구막힘 업체가 작성한 안내 톤으로 간결하게.`,
    `[중복 금지] 같은 안내축을 여러 번 반복 나열하지 마세요. 한 번만 정리.`,
  ].filter((l) => l !== null && l !== undefined).join('\n');
}

// ── 섹션별 유저 프롬프트 ─────────────────────
function buildUserPrompt(region, treatment, sectionKey) {
  const kw = treatment.name;
  const subject = region;
  const base =
    `🔒 주제 고정: "${kw}" 으로만 서술. 다른 주제 혼용 금지.\n` +
    `🔒 화자는 "${region} 하수구막힘 업체" 1인칭. 후기·체험담·시공후기·추천·보장·최저가 금지.\n` +
    `🔒 비용은 "영향 요소"로만, 정확한 금액 단정 금지.\n` +
    `🔒 "즉시해결/당일해결/확실히 해결/완벽 해결" 등 단정 표현 금지.\n\n`;

  const map = {
    intro:
      base +
      `[도입 — 상황 + 현장 진입]\n` +
      `전체 3문장. 첫 문장부터 "${region}" 현장에서 실제로 벌어진 상황 하나로 시작합니다. ` +
      `아래 서술은 전면 금지 — 막힘이 왜 생기는지 설명, 방치하면 생기는 문제, ${kw}의 일반적 필요성, 업종 소개. ` +
      `배경 설명 없이 상황 → 연락 → 현장 도착 순으로만 붙입니다. ` +
      `마지막 1문장은 배수구 앞으로 다가가 상태를 보러 가는 동작으로 닫습니다. 200자 내외.`,
    axis1:
      base +
      `[발생 원인 안내]\n${subject} ${kw}의 발생 원인을 설명하세요. ` +
      `음식물 찌꺼기·기름때·머리카락·이물질·배관 노후 등 어떤 원인이 있는지 정보로만. 기본범위/추가범위로 구분해 안내. 250자 내외.`,
    axis2:
      base +
      `[현장 — 작업 전개]\n` +
      `현장에서 막힌 구간을 뚫어 가는 동안 이어지는 동작을 순서대로 씁니다. ` +
      `현장 확인 → 배관 내시경 점검 → 고압세척·이물질 제거 → 배수 흐름 확인 순서를 지키되, ` +
      `각 단계를 항목으로 나열하지 말고 지금 손이 가고 눈이 가는 동작으로 서술하세요. ` +
      `단계마다 목적·원리·효과를 설명하지 않습니다. 250자 내외.`,
    infoblock:
      base +
      `[점검·확인 항목 정리]\n${kw} 관점에서 점검·확인할 항목을 목록으로 제시하세요. ` +
      `(배수 속도·역류 여부·악취·막힘 위치 구분 등) 단정 없이 "확인할 점"으로. 250자 내외.`,
    axis3:
      base +
      `[작업 장비·점검 안내]\n${subject} ${kw}에 사용하는 장비와 점검 방식을 설명하세요. ` +
      `고압세척기·배관 내시경·스프링/관통기·관로 탐지 등 장비별 역할을 정보로만. 250자 내외.`,
    axis4:
      base +
      `[현장 — 작업 후 최종 확인]\n` +
      `작업을 마친 뒤 현장에서 마지막으로 살펴보고 정리하는 장면을 씁니다. ` +
      `물을 다시 흘려 내려가는 속도를 보고, 연결부 주변에 남은 물기를 닦고, ` +
      `거름망을 제자리에 끼우면서 앞으로 무엇을 흘려보내지 않으면 되는지 짧게 한마디 건네는 동작까지 포함합니다. ` +
      `작업의 필요성이나 효과는 설명하지 않습니다. ` +
      `"이러한 확인을 통해 ~합니다" 같은 정리·결론 문장으로 닫지 말고, 마지막도 동작 그대로 끝냅니다. 250자 내외.`,
    closing:
      base +
      `[마무리]\n` +
      `총 3문장 이내, 150~250자. 이 분량을 절대 넘기지 마세요. 문단은 하나만 씁니다.\n` +
      `1문장 — 현장마다 배관 상태가 달라 직접 봐야 안다는 점.\n` +
      `2문장 — 확인해 볼 수 있는 구체 행동 한 가지.\n` +
      `새 주제를 꺼내지 말고, 앞 문단을 다시 설명하지 마세요. 홍보 문장 금지.`,
  };
  return map[sectionKey] || base;
}

// ── 이미지 alt ──────────────────────────────
function getImageAlts(region, treatment) {
  return [
    `${region} ${treatment.name} 작업 범위 안내`,
    `${region} 막힘 발생 원인 안내 자료`,
    `${region} 하수구막힘 상담 안내`,
  ];
}

export { FORBIDDEN, buildSystemPrompt, buildUserPrompt, getImageAlts };
