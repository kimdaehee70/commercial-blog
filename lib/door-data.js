// 부품군 입력 → 판단 재료 반환. 미입력·미매칭이면 null(프롬프트에 아무것도 붙지 않음).
export function getPartNote(input) {
  const v = String(input == null ? "" : input).trim();
  if (!v) return null;
  if (DOOR_CAUSE_PARTS[v]) return DOOR_CAUSE_PARTS[v];
  const hit = Object.values(DOOR_CAUSE_PARTS).find(
    (x) => x.label.includes(v) || x.parts.some((p) => v.includes(p))
  );
  return hit || null;
}

// 증상 입력 → 원형 보존. 미입력이면 빈 문자열(부작용 0).
export function formatSymptom(input) {
  const v = String(input == null ? "" : input).replace(/\s+/g, " ").trim();
  if (!v) return "";
  const hit = DOOR_SYMPTOMS.find((s) => v.includes(s));
  return hit || v;
}

