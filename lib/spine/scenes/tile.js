// ★ 경쟁 실측 근거: 상위 노출 글은 공간(욕실/주방/현관)이 아니라 공법 중심으로 설명이 흐른다.
//   그러나 전부 '설명형'이며 [빈소리로 범위를 재고 → 철거할지 덧방할지 정하는] 축이 비어 있다.
//   이 엔진의 핵심 축은 철거 ↔ 덧방 판단이다. arrive 가 그 판단으로 수렴한다.
