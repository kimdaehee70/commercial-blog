//      → 검색자는 '어떻게 할지'를 이미 정했다. arrive 첫 축 = 그 공법의 가능 여부 계측.
//   ② 손상 축 (타일부분보수·타일들뜸보수)
//      → 검색자는 손상 형태를 안다. arrive 첫 축 = 손상 범위 계측.
//   ③ 자재 축 (포세린타일시공)
//      → 검색자는 자재를 정했다. arrive 첫 축 = 대형판이 앉을 바탕 조건 계측.
