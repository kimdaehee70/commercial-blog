//     같은 cat에 흡수하면 동선 오염 → 부품 축 cat 으로 분리.
//     신규 토큰 치환: 장력 조절(screen 충돌)   → 벨트 팽팽함 맞춤
//                     커버 분리(airclean 부분문자열) → 상부 몰딩 커버 해체
//                     (door 관례 = '커버 해체' — 축/손잡이/힌지 커버와 동일 어휘)
//     14업종 교차검사: 완전일치 0 / 부분문자열 0. 풀리·벨트·팽팽·절단은 전 업종 최초 사용.
//   붙박이장 슬라이딩도어수리 → 붙박이장도어수리
//     ('슬라이딩도어수리'의 부분문자열이라 titleEngine pickSymptom LEX 누수 — 세션62 방장판 사례 동형)
//
// ★ 수리군 분리 원칙:
//   방충망(screen) = 망·프레임 축 / 에어컨청소(airclean) = 분해·세척 축
//   도어(door)     = 구동 부품 축(롤러·레일·호차·힌지·래치·클로저)
//   → screen의 '개폐 확인 · 장력 조정', airclean의 '조립 · 작동 확인'과 의미가 겹치므로
//     door는 '여닫힘 확인 · 작동 테스트'로 분리한다.
//
// ★ 15업종 토큰 교차검사 중복 0.
//   충돌 회피 치환 이력:
//     현장 도착(전 업종 공유)       → 출동 도착   ※ door는 출장 수리라 '출동'이 동선의 시작
//     개폐 확인(screen)             → 여닫힘 확인
//     작동 확인(airclean·systemair) → 작동 테스트
//     작업 범위 결정(다수)          → 원인 판단 / 교체 여부 판단
