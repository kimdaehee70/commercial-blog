//      → 검색자는 증상만 안다. arrive 첫 축 = '증상 재현'.
//   ② 부품 축 (문손잡이·도어클로저·힌지·롤러레일)
//      → 검색자는 원인을 이미 안다. arrive 첫 축 = '규격·체결 방식 확인'.
//   두 축은 같은 Spine을 쓰되 진입 지점이 다르다.
//
// ★ 통합·개명 이력:
//   롤러 + 레일 → 롤러레일교체 1개  (분리 시 work 동선이 거의 동일 → 동선 복제 위험)
//   [세션64] 중문벨트교체 신설 (11 → 12 cat). 기존 11cat 무수정.
