// ★ 토큰은 문장이 아니라 '행동 단위'. prompts.js가 Scene 문장으로 전개한다.
// ★ arrive = 현장 진입·발견·진단(axis1) / work = 보양·시공·검수(axis2)
// ★ 업종 간 토큰 공유 금지 (Naver 전략2 구조 다양성).
//   [세션68] 신설. 복제 베이스 = scenes/tile.js (Construction V3).
//
// ★ Window Spine — 창이 달라도 판단은 하나다.
//   Discovery → Diagnosis → 부분보수/전체교체 판단 → 철거·정리 → 설치 → 실링 → 기밀 검수
//   arrive: 진입 → 외풍·결로 흔적 → 프레임·부속 상태 → 실측 → 교체 범위 판단
//   work:   보양 → 기존 부속 걷기 → 개구부 정리 → 자재 설치 → 실리콘 마감 → 기밀·개폐 확인
//
// ★ 경쟁 실측 근거: 상위 노출 글은 창호 종류와 자재 등급(이중창·시스템창호·유리 사양) 소개로 흐른다.
//   전부 '설명형'이며 [외풍이 어디서 들어오는지 찾아 → 창을 갈지 틈을 막을지 정하는] 축이 비어 있다.
//   이 엔진의 핵심 축은 창을 통째로 가느냐 / 새는 자리만 잡느냐다. arrive 가 그 판단으로 수렴한다.
//
// ★ cat 축이 셋으로 갈린다 — arrive 첫 축을 분리해 동선 복제를 차단한다.
//   ① 교체 축 (샷시교체·복층유리교체)
//      → 검색자는 '무엇을 갈지' 정했다. arrive 첫 축 = 실측·규격 확인.
//   ② 손상 축 (창문누수수리·창틀실리콘교체)
//      → 검색자는 증상을 안다. arrive 첫 축 = 물·틈이 지나간 자리 계측.
//   ③ 단열·부착 축 (창문단열시공·방범창설치)
//      → 검색자는 창 자체가 아니라 창 주변을 손보려 한다. arrive 첫 축 = 창 주변 조건 계측.
//   세 축은 같은 Spine을 쓰되 진입 지점이 다르다. (tile 공법/손상/자재 축과 동형)
//
// ★ 「방충망교체」를 cat 으로 두지 않은 근거 (세션68 실측):
//   screen 업종이 이미 「교체」cat 을 보유하며 동선이 사실상 동일하다.
//     screen 교체 work = 기존 망 분리 → 프레임 정리 → 고무바킹 제거 → 신규 망 재단 →
//                        망 고정 → 장력 조정 → 프레임 재장착 → 개폐 확인
//   window 에 같은 cat 을 두면 업종 간 검색축 자기잠식 + 토큰 대량 충돌이 발생한다.
//   → 방충망은 screen 엔진이 소유한다. window 는 「샷시와 함께 교체」 결합 의도만
//     keywords / titlePatterns 로 흡수한다(세션64 원칙: 용도·결합은 검색축, cat 은 작업축).
//   ★ 역방향 근거: SCREEN_BLOCK_KEYWORDS 에 "창호 교체·샷시 교체·이중창·시스템창호"가
//     이미 등록돼 있다. screen 이 창호 축을 배제해 둔 상태이므로 경계는 이미 합의돼 있다.
//
// ★ 「창문단열시공」을 샷시교체에 합치지 않은 근거:
//   검색축(결로·곰팡이·외풍·부분단열·이보드·우레탄폼)과 동선이 모두 다르다.
//   work 첫 3토큰 = 창가 벽지 뜯어내기 → 우레탄폼 충진 상태 보기 → 이보드 재단.
//   창을 건드리지 않고 창 주변 벽체를 여는 공정이라 교체 축과 겹치지 않는다.
//
// ★ 인접 업종 분리 — 창 주변을 다루는 업종이 넷이다:
//   방충망(screen)      = 망·프레임 축(망 재단·장력·고무바킹)
//   인테리어필름(film)  = 표면 부착 축(샷시필름 = 프레임에 필름을 씌움)
//   방수공사(waterproof)= 방수층 축(외벽 크랙·창틀 코킹은 외벽방수 cat 소유)
//   창호시공(window)    = 개구부 축(창짝·프레임·유리·기밀)
//   → window 의 전문성 판별 축은 자재가 아니라 '어디로 새는가를 찾아내는가'다.
//
// ★ 18업종 토큰 교차검사 완전일치 0 / 부분문자열 0.
//   충돌 회피 치환 이력:
//     현장 도착(공사군 공유)                   → cat별 계측 토큰으로 개별화
//     창호 규격 실측(screen)                    → 개구부 안목 재기 / 유리 두께 재기
//     프레임 변형 확인(screen)                  → 프레임 휨 눈으로 훑기
//     기존 망 분리 / 프레임 정리(screen)         → 창짝 들어내기 / 개구부 잔재 걷기
//     장력 조정(screen)                         → 미사용
//     개폐 확인(screen) / 여닫힘 확인(door)      → 여닫아 보며 저항 보기
//     기존 실리콘 제거(film)                     → 커터로 실리콘 따내기
//     이음부 실리콘 재시공(film)                 → 외부 코킹 다시 쏘기
//     프레임 결로 자국 확인(film)                → 창가 물자국 위치 보기
//     창틀 코킹 확인 / 노후 코킹 제거(waterproof) → 코킹 갈라짐 짚어보기 / 외부 코킹 걷어내기
//     살수 누수 시험(waterproof)                 → 물 뿌려 새는 자리 보기
//     굳는 시간 두기(tile)                        → 실리콘 경화 대기
//     보양 작업(coating·interior)                → 창 주변 비닐 치기 / 바닥 천 깔기
