// lib/spine/scenes/waterproof.js
// Scene 토큰 전담 — 방수공사(waterproof) 업종 cat별 현장 동선
// ★ 콘텐츠 계층. 엔진(resolver/fallback/validation)은 lib/spine/sceneSpine.js.
// ★ 토큰은 문장이 아니라 '행동 단위'. prompts.js가 Scene 문장으로 전개한다.
// ★ arrive = 현장 진입·발견·진단(axis1) / work = 보양·시공·검수(axis2)
// ★ 업종 간 토큰 공유 금지 (Naver 전략2 구조 다양성).
//   [세션65] 신설. 복제 베이스 = scenes/door.js (Construction V3).
//
// ★ Waterproof Spine — 부위가 달라도 동선은 하나다.
//   Discovery → Diagnosis → Method → Protect → Apply → Test
//   arrive: 진입 → 누수 흔적 → 원인 발견 → 손상 범위 → 공법 판단
//   work:   보양 → 기존층 처리 → 바탕 정리 → 보강 → 도포/부착 → 양생 → 누수 시험 → 인계
//
// ★ 경쟁 실측 근거: 상위 노출 글의 축은 ①공법 홍보 ②오래가는 방수 ③견적 ④공사 순서.
//   전부 '설명형'이며 [발견 → 판단 → 공법 선택] 축이 비어 있다.
//   이 엔진은 설명형이 아니라 현장 진행형으로 간다. arrive 가 그 차이를 만든다.
//
// ★ cat 축이 셋으로 갈린다 — arrive 첫 축을 분리해 동선 복제를 차단한다.
//   ① 부위 축 (옥상·외벽·베란다·화장실·지하주차장)
//      → 검색자는 '어디서 물이 샌다'만 안다. arrive 첫 축 = 누수 흔적 위치 확인.
//   ② 손상 축 (균열보수·인젝션방수)
//      → 검색자는 손상 형태를 이미 안다. arrive 첫 축 = 손상 형태·규모 계측.
//   ③ 공법 축 (우레탄방수·PVC시트방수)
//      → 검색자는 공법을 이미 정했다. arrive 첫 축 = 기존 방수층 상태 확인.
//   세 축은 같은 Spine을 쓰되 진입 지점이 다르다. (door 의 문종류축/부품축과 동형)
//
// ★ 공법 축을 부위 cat 안으로 흡수하지 않은 근거:
//   우레탄(도막)과 PVC시트(부착)는 work 첫 3토큰이 완전히 다르다.
//     우레탄  = 기존 도막 벗기기 → 바탕면 습기 말리기 → 파인 자리 메움
//     PVC시트 = 바탕면 돌출물 정리 → 부직포 절연층 깔기 → 시트 재단
//   [인수계 세션64 원칙] arrive 가 비슷해도 work 첫 3토큰이 다르면 별도 cat.
//
// ★ 인접 업종 분리:
//   탄성코트(coating) = 외벽 미관 도막 축 / 누수탐지(leakdetect) = 탐지·계측 축
//   방수공사(waterproof) = 방수층 축(도막·시트·지수제·양생·담수시험)
//   → coating 의 '도포', leakdetect 의 '누수 지점 확인' 과 의미가 겹치므로
//     waterproof 는 '하도/중도/상도' 층 어휘와 '담수 누수 시험'으로 분리한다.
//
// ★ 충돌 회피 치환 이력 (door.js 실측 어휘 기준):
//     현장 도착(전 업종 공유) / 출동 도착(door) → 부위별 진입 토큰으로 개별화
//     프라이머 도포(film 계열)                  → 바탕 프라이머 흡수
//     작업 범위 결정(다수) / 원인 판단(door)    → 시공 범위 판단 / 보수 방식 판단
//     고객 확인(moving·grout) / 고객 인계(door) → 시공 내역 설명
//     작동 테스트(door)                          → 담수 누수 시험 / 살수 누수 시험
//     줄눈 시공(grout)                           → 타일 줄눈 채움
//     장력 조절(screen)                          → 미사용

