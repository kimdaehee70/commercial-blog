// ============================================================
// 0. DIRECTION 헬퍼 — 데이터 조합으로 동적 생성
// ============================================================
export function getCafeDirection(treatment, situation, purpose) {
  if (!treatment) {
    return buildDirection({ menu: '', situation, purpose });
  }
  const menu = treatment.menu || treatment.menuRef || '';
  return buildDirection({ menu, situation, purpose });
}

