function getAiSmellGuide() {
  return (
    "\n[AI 티 제거]\n" +
    "- '정리하면/결론적으로/따라서/체계적인/살펴보겠습니다' 금지\n" +
    "- 같은 문장 구조 3회 연속 반복 금지\n" +
    "- 지역+진료명 결합은 글 전체 3회 이하, 이후 '이 진료/해당 진료/여기서'로 자연 치환\n"
  );
}

// ============================================================
// 빌더 진입점 — 섹션별 (정보형)
//   playConfig 섹션 키: concern / situation / consult / reason / result / closing
// ============================================================
export function buildPediatricsPrompt(section, treatment, region, options = {}) {
  switch (section) {
    case "concern":   return _concern(treatment, region);
    case "situation": return _search(treatment, region);
    case "consult":   return _process(treatment, region);
    case "reason":    return _compare(treatment, region);
    case "result":    return _manage(treatment, region);
    case "closing":   return _closing(treatment, region);
    // v1 호환 키 (혹시 남아 있을 경우 매핑)
    case "search":    return _search(treatment, region);
    case "decision":  return _compare(treatment, region);
    default:          return "";
  }
}

function _concern(treatment, region) {
  const name = treatment.name;
  const dir  = getPediatricsDirection(name, treatment);
  return (
    "[섹션: 이런 증상일 때 | 최소 220자]\n" +
    "진료명: " + name + " | 지역: " + region + "\n" +
    "🔒 이 진료가 고려되는 배경: " + dir.concern + "\n\n" +
    "[성격 — 정보형 (개인 사연 아님)]\n" +
    "- 특정 아이 이야기가 아니라, 이 진료가 어떤 증상·상황에서 고려되는지 일반 정보로 설명.\n" +
    "- '한 아이는/저희 아이는 ~했다' 식 이야기 시작 금지. 보호자 1인칭 금지.\n\n" +
    "[작성 방향]\n" +
    "- 이 진료가 일반적으로 고려되는 증상·상황을 사실 기술로 정리\n" +
    "- \"" + dir.hook + "\" 같은 상황에서 이 진료를 알아보게 된다는 식으로 일반화\n" +
    "- 어미 다양화 (동일 어미 3회 연속 금지), 1인칭 금지, 감정 과장 최소화\n" +
    getAiSmellGuide() +
    "\n[마지막 문장]\n" +
    "- '이런 상황에서 " + name + "을(를) 알아보게 됩니다' 정도의 정보형 문장으로 마무리.\n"
  );
}

function _search(treatment, region) {
  const name = treatment.name;
  const dir  = getPediatricsDirection(name, treatment);
  return (
    "[섹션: 진료 알아보기 | 최소 200자]\n" +
    "진료명: " + name + " | 지역: " + region + "\n" +
    "🔒 이 진료로 확인·관리하는 대상: " + dir.target + "\n\n" +
    "[성격 — 정보형 (탐색 여정 서사 아님)]\n" +
    "- '검색했다/맘카페를 뒤졌다/여러 병원을 비교했다' 식 개인 행동 서술 금지.\n" +
    "- 이 진료(" + dir.keyword + ")가 무엇을 확인·관리하는지 설명.\n\n" +
    "[작성 방향]\n" +
    "- 이 진료가 확인·관리하는 대상(" + dir.target + ")을 사실 기술\n" +
    "- 소아청소년과가 증상·성장·감염·예방접종을 관리하는 1차 진료 창구로서 어떤 역할을 하는지 정보형으로\n" +
    "- 지역명은 필요 시 1회 정도만\n" +
    getAiSmellGuide()
  );
}

function _process(treatment, region) {
  const name    = treatment.name;
  const compare = treatment.compareWith || "다른 접근";
  const info    = INFO_BLOCKS[name] || null;
  const examList = (info && info.examItems && info.examItems.join(" → ")) || "문진·시진·기본 검사";
  return (
    "[섹션: 진료 진행 방식 | 최소 250자]\n" +
    "진료명: " + name + " | 비교 접근: " + compare + " | 지역: " + region + "\n\n" +
    "[성격 — 정보형 (진료 장면 서술 아님)]\n" +
    "- '상담에서는 ~한다 / 의사가 ~했다 / 선생님이 ~라고 하셨다' 식 장면·인용 서술 금지. 진료 진행 방식 자체를 설명.\n\n" +
    "[필수 포함 — 항목 설명 형식]\n" +
    "✔ 진료 전 문진·기본 확인 안내 (해당 시)\n" +
    "✔ 확인·검사 항목을 항목 설명 형식으로: " + examList + "\n" +
    "✔ 진료·검사·관리가 진행되는 일반 흐름은 '대체로 ~' 형태로 위임\n" +
    "✔ 필요 시 추가 검사나 전문 진료 연계가 이뤄질 수 있다는 점을 일반 정보로\n" +
    "✔ 비용은 \"진료 항목에 따라 안내됩니다\"로 표기 (직접 가격 금지)\n" +
    "- 특정 약물·주사·백신의 효과 홍보 금지. 관리 방향은 일반 정보로만.\n" +
    getAiSmellGuide()
  );
}

function _compare(treatment, region) {
  const name    = treatment.name;
  const compare = treatment.compareWith || "다른 접근";
  const info    = INFO_BLOCKS[name] || null;
  const infoTitle = (info && info.compareTitle) || (name + " vs " + compare);
  const infoItems = (info && info.compareItems) || [];
  const infoBlock = infoItems.length
    ? "\n- 아래 비교 정보를 글에 자연스럽게 녹여 \"정보 블럭\" 역할을 하게 할 것 (표 나열 아님, 문단 안 정보형 서술):\n" +
      "  ▸ " + infoTitle + "\n  " +
      infoItems.map((it, i) => (i + 1) + ". " + it).join("\n  ")
    : "";
  return (
    "[섹션: 함께 고려하는 부분 | 최소 200자]\n" +
    "진료명: " + name + " | 비교 접근: " + compare + "\n\n" +
    "[성격 — 정보형 (개인 결정 서사 아님)]\n" +
    "- '~하기로 결정했다 / ~를 선택한 이유' 식 개인 결정 서사 금지.\n" +
    "- " + name + "과(와) " + compare + "이(가) 함께 고려되는 기준 자체를 설명.\n" +
    infoBlock + "\n\n" +
    "[작성 방향]\n" +
    "- 두 접근의 목적·적용 상황 차이를 사실 기술 (우열 단정 금지)\n" +
    "- 어떤 상황에서 어떤 접근이 먼저 고려되는지 일반 기준으로 안내\n" +
    "- 소아청소년과에서 먼저 확인·관리 후 필요 시 전문 진료로 연계된다는 점을 정보형으로\n" +
    getAiSmellGuide()
  );
}

function _manage(treatment, region) {
  const name = treatment.name;
  const dir  = getPediatricsDirection(name, treatment);
  return (
    "[섹션: 관리와 경과 안내 | 최소 280자]\n" +
    "진료명: " + name + " | 지역: " + region + "\n" +
    "🔒 확인·관리 대상: " + dir.target + "\n\n" +
    "[성격 — 정보형 (효과 단정·성과 홍보 금지)]\n" +
    "- 진료 후 관리·경과 확인이 이뤄지는 일반 흐름을 설명.\n" +
    "- '완치됩니다/나았습니다/효과가 좋습니다' 같은 성과 단정 절대 금지 — 경과는 아이마다 개인차가 있음을 안내.\n" +
    "- 발달·행동·예방접종 관련 항목은 특히 '관찰·확인' 수준으로만 서술.\n\n" +
    "[작성 방향]\n" +
    "- 진료 → 관리 방향 안내 → 경과 확인 → 필요 시 재진료로 이어지는 일반 흐름 정보형 서술\n" +
    "- 관리에서 확인하는 항목(" + dir.target + ")을 일반 정보로 안내\n" +
    "- 꾸준한 관리·생활 습관 병행이 필요할 수 있다는 점을 일반 안내로 (효과 보장 금지)\n" +
    "- 구체 시간표(D+1/1주/2주) 나열 금지 — 흐름 위주로\n" +
    getAiSmellGuide()
  );
}

function _closing(treatment, region) {
  const name = treatment.name;
  return (
    "[섹션: 마무리 | 최소 180자]\n" +
    "진료명: " + name + " | 지역: " + region + "\n\n" +
    "[작성 방향]\n" +
    "- 이 진료가 어떤 증상·상황에서 고려되는지 정보형으로 요약\n" +
    "- 정확한 진료 필요 여부·범위는 진료 상담에서 안내된다는 중립 문장으로 마무리\n" +
    "- CTA(예약/방문 유도) 금지, 광고 어휘 금지, 1인칭·보호자 후기 톤 금지\n" +
    getAiSmellGuide()
  );
}

