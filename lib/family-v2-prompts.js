export function buildFamilyPrompt(sectionKey, treatment, region) {
  const d = FAMILY_DIRECTION[treatment.id];
  if (!d) throw new Error("FAMILY_DIRECTION 누락: " + treatment.id);
  const fn = SECTION_BUILDERS[sectionKey];
  if (!fn) throw new Error("SECTION_BUILDERS 누락: " + sectionKey);
  return fn(d, treatment, region);
}

