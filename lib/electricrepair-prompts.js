// ── 섹션별 유저 프롬프트 ─────────────────────
//   섹션: intro / cause(원인) / area(점검위치) / infoblock(체크) / process(진행절차) / manage(관리방법) / closing
function buildUserPrompt(region, treatment, sectionKey) {
  const kw = treatment.name;
  const base =
    `🔒 주제 고정: "${kw}" 으로만 서술. 다른 주제·업종 혼용 금지.\n` +
    `🔒 화자는 "${region} 전기수리 업체" 1인칭. 후기·작업일지형(다녀왔습니다·고쳐드렸습니다·출동했습니다·당일출동·전문가가 직접)·추천·보장·최저가·할인·순위·출장·24시 금지.\n` +
    `🔒 타업종 금지(집수리·수도설비·보일러·방충망·건물청소). 면허 전기공사(분전반 증설·배선공사·승압) 금지. 비용은 "영향 요소"로만, 정확한 금액 단정 금지. 작업·점검 전 안전 확인 안내.\n\n`;

  const map = {
    intro:
      base +
      `[도입 — 상황 + 현장 진입]\n` +
      `전체 3문장. 첫 문장부터 "${region}" 현장에서 실제로 벌어진 생활 속 상황 하나로 시작합니다. ` +
      `아래 서술은 전면 금지 — 전기 설비가 어떤 것인지 설명, 방치하면 생기는 문제, "${kw}"의 일반적 필요성, 업종 소개. ` +
      `배경 설명 없이 상황 → 연락 → 현장 도착 순으로만 붙입니다. 과거 회상형이 아니라 현재 진행형으로 씁니다. ` +
      `마지막 1문장은 해당 부위 앞으로 다가가 상태를 보러 가는 동작으로 닫습니다. 200자 내외.`,
    cause:
      base +
      `[발생 원인 안내]\n${region} ${kw} 관점에서 왜 이런 증상·문제가 발생할 수 있는지 설명하세요. ` +
      `누전·과부하·노후·접촉 불량·발열·오작동 중 관련 원인으로. 단정 없이 "원인일 수 있는 점"으로. 250자 내외.`,
    area:
      base +
      `[점검 위치 / 확인 항목]\n${kw} 관점에서 어디를 점검하고 무엇을 확인하는지 설명하세요. ` +
      `차단기·콘센트·스위치·소켓·배선·습기 구역 중 관련 위치로. ` +
      `단정 없이 "확인하는 부분"으로. 250자 내외.`,
    infoblock:
      base +
      `[체크포인트 정리]\n${kw} 관점에서 확인할 항목을 목록으로 제시하세요. ` +
      `안전 확인(차단기 차단 등) 포함. 단정 없이 "확인할 점"으로. 250자 내외.`,
    process:
      base +
      `[현장 — 작업 전개]\n` +
      `현장에서 점검과 작업이 진행되는 동안 이어지는 동작을 순서대로 씁니다. ` +
      `현장확인 → 원인 점검 → 안전 차단 → 교체·보수 → 작동 확인 중 이 주제에 해당하는 단계만 순서대로 지키되, ` +
      `각 단계를 항목으로 나열하지 말고 지금 손이 가고 눈이 가는 동작으로 서술하세요. ` +
      `차단기를 내리는 동작은 빠뜨리지 말고 실제 동작으로 포함합니다. ` +
      `단계마다 목적·원리·효과를 설명하지 않습니다. 300자 내외.`,
    manage:
      base +
      `[현장 — 작업 후 최종 확인]\n` +
      `작업을 마친 뒤 현장에서 마지막으로 살펴보고 정리하는 장면을 씁니다. ` +
      `차단기를 다시 올려 전원이 들어오는지 보고, 해당 부위를 눌러 보거나 켜 보며 작동과 발열을 확인하고, ` +
      `주변을 정리하는 동작으로 이어 갑니다. ` +
      `평소 살펴 두면 되는 부분은 그 내용을 문장으로 그대로 씁니다 — "한마디 건넵니다", "안내합니다" 같이 말하는 행위 자체를 서술하는 표현은 쓰지 마세요. ` +
      `작업의 필요성이나 효과는 설명하지 않습니다. ` +
      `"이러한 확인을 통해 ~합니다" 같은 정리·결론 문장으로 닫지 말고, 마지막도 동작 그대로 끝냅니다. 300자 내외.`,
    closing:
      base +
      `[마무리]\n` +
      `총 3문장 이내, 150~250자. 이 분량을 절대 넘기지 마세요. 문단은 하나만 씁니다.\n` +
      `1문장 — 집집마다 배선과 사용 환경이 달라 직접 봐야 안다는 점.\n` +
      `2문장 — 확인해 볼 수 있는 구체 행동 한 가지.\n` +
      `새 주제를 꺼내지 말고, 앞 문단을 다시 설명하지 마세요. 홍보 문장 금지.\n` +
      `🔒 "안녕하세요" 등 인사로 글을 새로 시작하지 말 것.`,
  };
  return map[sectionKey] || base;
}

