// ── 섹션별 유저 프롬프트 ─────────────────────
function buildUserPrompt(region, treatment, sectionKey, aptName) {
  const kw = treatment.name;
  const base =
    `🔒 주제 고정: "${kw}" 으로만 서술. 다른 주제·방역·청소 혼용 금지.\n` +
    `🔒 화자는 "${region} 비둘기퇴치 업체" 1인칭. 후기·체험담·시공일지·고객사례·추천·보장·박멸 보장 금지.\n` +
    `🔒 포획·독극물·살처분·천적·민원·행정처분 일절 금지. 물리적 차단·위생·예방 관점만.\n` +
    `🔒 비용은 "영향 요소"로만, 정확한 금액·견적 단정 금지. 효과는 "차단·예방·관리"로만.\n\n`;

  const map = {
    intro:
      base +
      `[도입 — 장면]\n` +
      `설명으로 시작하지 말고 장면으로 시작하세요. "${region}"에서 ${kw}을(를) 알아보게 되는 순간을 하나만 골라, ` +
      `눈에 보이는 상태와 들리는 소리·냄새 위주로 2~3문장으로 씁니다. ` +
      `원인 설명·범위 나열·항목 열거 금지. 250자 내외.`,
    axis1:
      base +
      `[현장 확인 — 장면]\n어디까지 막을지 정하기 전에 현장을 둘러보는 장면으로 쓰세요. ` +
      `개구부와 틈새를 올려다보고, 실외기 뒤쪽을 들여다보고, 난간과 상부에 남은 흔적을 확인하고, ` +
      `깃털·둥지 재료가 모인 자리를 짚어 보는 동작을 이어서 서술합니다. ` +
      `마지막 문장은 "확인한 자리를 바탕으로 어디까지 막을지 범위를 정한다" 식의 행동으로 닫습니다.\n` +
      `🔒 "차단 범위는/기본 범위는/추가 범위는" 같은 나열·설명 문장 금지.\n` +
      `🔒 첫 문장은 도착해서 바로 살펴보는 동작으로 시작할 것. "~하기 위해/~를 결정하기 위해" 같은 목적 설명으로 열지 말 것. 250자 내외.`,
    axis2:
      base +
      `[발생 원인 안내]\n${kw}과 관련된 비둘기 유입 원인을 설명하세요. ` +
      `귀소본능(반복 회귀)·은신 공간·먹이 환경 중심으로. 250자 내외.`,
    infoblock:
      base +
      `[체크포인트 정리]\n${kw} 관점에서 확인할 항목을 목록으로 제시하세요. ` +
      `(차단 범위·배설물 위생·차단 시설 점검·재유입 경로 등) 단정 없이 "확인할 점"으로. 250자 내외.`,
    axis3:
      base +
      `[작업 진행 — 현장 장면]\n${kw} 작업이 진행되는 현장을 순서대로 보여주세요. ` +
      `단계 목록이 아니라, 현장에서 무엇을 걷어내고 무엇을 씻어내고 무엇을 대어 고정하는지 ` +
      `손의 동작과 눈으로 확인하는 상태 중심으로 씁니다. ` +
      `사전 점검 → 배설물 청소·소독 → 차단 시설(망·버드스파이크) 설치 → 마감 점검 흐름만. ` +
      `"~단계입니다" 식 설명 문장 금지. 300자 내외.\n` +
      `🔒 "다음으로/이후에는" 같은 연결어로 설명을 잇지 말 것. 한 문단에 몰아넣지 말고 ` +
      `점검 / 청소·소독 / 설치 / 마감확인 을 짧은 문단으로 끊어서 쓸 것(문단당 2~3문장).\n` +
      `🔒 "안내하며/설명드리며/중요하다는 점을 알리며" 등 말하는 행위 자체를 서술하는 표현 금지. 마지막은 눈으로 확인하는 동작으로 닫을 것.\n` +
      `🔒 "특히 ~은 ~하므로 ~할 필요가 있습니다" 같은 설명 문장 금지. 대상 장소는 살펴보는 동작 안에서 언급할 것.`,
    axis4:
      base +
      `[작업 후 확인 — 현장 장면]\n작업을 마친 뒤 현장에서 함께 확인하는 장면으로 쓰세요. ` +
      `망을 손으로 당겨 고정 상태를 보고, 남은 자국이 지워졌는지 바닥을 살피고, ` +
      `옆 개구부와 인접한 틈을 다시 올려다보고, 언제 다시 살펴보면 되는지 자리를 짚어 두는 식의 동작 중심으로. ` +
      `배설물·악취 위생 관리 / 차단 시설 정기 점검 / 재유입 경로 확인 세 가지는 반드시 동작 안에 녹여서 담습니다. ` +
      `목록 나열·설명형 금지. 동작으로 문장을 끝낼 것(평가·소감으로 닫지 말 것). 300자 내외.\n` +
      `🔒 "말씀드립니다/당부합니다/한마디 건넵니다" 등 말하는 행위 자체를 서술하는 표현 금지.`,
    closing:
      base +
      `[마무리]\n총 3문장 이내, 150~250자, 문단 1개로만 씁니다.\n` +
      `1문장 = 현장마다 구조와 상태가 달라 직접 봐야 알 수 있다는 취지.\n` +
      `2문장 = 눈에 띄는 흔적이 반복될 때 그대로 두지 말고 상태부터 확인해 보라는 행동 1가지.\n` +
      `판단·평가·소감이 아니라 행동으로 문장을 끝낼 것. 마지막 문장을 "이를 통해 ~할 수 있습니다" 식 효과 설명으로 닫지 말 것.\n` +
      `🔒 "안녕하세요" 등 인사로 글을 새로 시작하지 말 것. 소제목·목록·재서술 금지. "추천합니다/권해드립니다" 표현 금지.`,
  };
  return map[sectionKey] || base;
}

