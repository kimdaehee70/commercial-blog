// ────────────────────────────────────────────────────────────
// 4. 메인 함수 — 현재 업종 기준 차단 리스트 생성
//   currentIndustry: "dental" 등 INDUSTRY_TOKENS의 키
//   extraExempt: 추가 면제 토큰 (런타임에 추가 가능)
//   리턴: 이 업종이 차단해야 할 다른 과 키워드 배열
// ────────────────────────────────────────────────────────────
export function getCrossBlocks(currentIndustry, extraExempt = []) {
  if (!INDUSTRY_TOKENS[currentIndustry]) {
    console.warn(`[industryBlocks] 알 수 없는 업종: ${currentIndustry}`);
    return [];
  }

  // 면제 토큰 합집합 (현재 업종 자기 자신 + EXEMPTIONS + extraExempt)
  const exemptSet = new Set([
    ...INDUSTRY_TOKENS[currentIndustry],
    ...(EXEMPTIONS[currentIndustry] || []),
    ...extraExempt,
  ]);

  // 다른 모든 과 토큰 모음 (면제 제외)
  const blocks = [];
  for (const [ind, tokens] of Object.entries(INDUSTRY_TOKENS)) {
    if (ind === currentIndustry) continue;
    for (const t of tokens) {
      if (!exemptSet.has(t)) blocks.push(t);
    }
  }
  return blocks;
}

// ────────────────────────────────────────────────────────────
// 5. 디버그 헬퍼 (옵션) — 침투 의심 시 콘솔 경고만 출력
//   forEach로 빈 문자열 제거 시 함께 호출하면, 차단된 토큰 카운트
// ────────────────────────────────────────────────────────────
export function logCrossBlockHits(text, currentIndustry, extraExempt = []) {
  const blocks = getCrossBlocks(currentIndustry, extraExempt);
  const hits = blocks.filter(t => text.includes(t));
  if (hits.length > 0) {
    console.warn(`[${currentIndustry}] 타과 침투 감지: ${hits.join(", ")}`);
  }
  return hits;
}
