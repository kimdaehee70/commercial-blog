// 누수탐지(leakdetect) prompts — v1
// 방향: 정보형 + 원인·절차·장비 안내 가이드형 / 원인·탐지절차·탐지장비·공사범위·보험·예방 축
// 화자 = {region} 누수탐지 업체 1인칭. 후기형·체험담·추천 금지.
// ★ 누수탐지 전용 절대 금지:
//    최저가/보장/업계최고/전국1위/100% 해결 / 내돈내산·시공후기 / 만족도
// 복제 베이스: tankclean-prompts.js (정보형 섹션 프롬프트 구조)

// ── 금칙어 (과장·후기·보장·추천) ───────────
const FORBIDDEN = [
  // 과장·광고
  '최저가', '무조건', '업계 최고', '업계최고', '1등 업체', '1위', '전국1위', '최고',
  '역대급', '초대박', '대박', '100% 해결', '100퍼센트 해결', '완벽',
  // 보장·추천 (정보형 고정)
  '보장', '추천드립니다', '강력 추천', '강력추천', '추천 업체', '강추',
  // 후기·체험담
  '직접 해봤', '내돈내산', '시공후기', '리얼후기', '후기입니다', '고객님 후기', '만족도',
  // AI 논문형 연결어
  '따라서', '결론적으로', '정리하면',
];

// ── 분석축 라벨 (treatment.analysisAxis가 없을 때 fallback) ──
const DEFAULT_AXIS = ['누수 원인', '탐지 절차', '탐지 장비', '공사 범위', '예방 관리'];

// ── 시스템 프롬프트 ─────────────────────────
function buildSystemPrompt(region, treatment, aptName, aptMeta) {
  const kw = treatment.name;
  const axis = (treatment.analysisAxis && treatment.analysisAxis.length)
    ? treatment.analysisAxis : DEFAULT_AXIS;
  const subject = aptName ? `${region} ${aptName}` : region;
  const metaLine = (aptMeta && (aptMeta.livingArea || aptMeta.station))
    ? `[단지 컨텍스트] ${aptName}은 ${aptMeta.livingArea || ""}${aptMeta.station ? `, ${aptMeta.station} 인근` : ""}입니다. 생활권·접근성은 이 정보를 자연스럽게 활용하되 누수탐지 안내가 주제임을 잊지 마세요.`
    : "";
  return [
    `당신은 ${region}에서 누수탐지를 안내하는 업체입니다.`,
    `화자는 "${region} 누수탐지 업체" 1인칭으로 고정합니다. 업체명·상호는 본문에 쓰지 않습니다.`,
    ``,
    metaLine || null,
    `[글의 성격]`,
    `- 정보 안내형 글입니다. ${aptName ? `"${aptName}" ${kw}를` : `"${region}" ${kw}를`} 누수 원인·탐지 절차·탐지 장비·공사 범위 기준으로 차분히 설명합니다.`,
    `- 후기형(체험담·내돈내산·시공후기)은 쓰지 않습니다. 정보 안내 톤으로만.`,
    `- 손님이 "누수 원인·탐지 절차·점검 항목"을 알 수 있게 돕는 가이드 톤.`,
    ``,
    `[누수탐지 절대 금지 — 반드시 지킬 것]`,
    `- 과장·광고 금지: "최저가/업계최고/전국1위/100% 해결" 등 단정 금지.`,
    `- 보장·추천 단정 금지: "보장합니다/강력추천" 금지. "확인할 점" 수준의 정보로만.`,
    `- 후기·체험담 금지: "직접 해봤/내돈내산/시공후기/만족도" 금지. 1인칭 체험 서술 금지.`,
    `- 비용 단정 금지: 정확한 금액 단정 금지. "누수 위치·배관 유형·공사 범위에 따라 달라지는 요소"로만.`,
    `- 해결 보장 과장 금지: "100% 해결/무조건 잡는다" 단정 금지. 현장 확인·탐지 절차 안내 톤으로.`,
    ``,
    `[안내축 — 이 축으로 서술]`,
    axis.map((a) => `- ${a}`).join('\n'),
    ``,
    `[키워드]`,
    `- 핵심: "${kw}" 자연스럽게 반복(과밀 금지).`,
    `- 지역: "${subject}" 형태를 글 전체 3회 이하로. 이후 "이 현장/이 지역/현장" 자연 치환.`,
    ``,
    `[필수 요소]`,
    `- 누수 원인(배관 노후·방수층 손상·이음부 균열 등)`,
    `- 탐지 절차(현장 확인 → 의심 구간 점검 → 위치 특정 → 범위 판단)`,
    `- 탐지 장비(열화상카메라·청음 탐지·가스 탐지·배관 내시경)`,
    `- 공사 범위 또는 보험 처리·예방 관리`,
    `- 비용은 "영향 요소"로만 설명(특정 금액 단정 금지).`,
    ``,
    `[금지]`,
    FORBIDDEN.map((w) => `- "${w}"`).join('\n'),
    `- 광고형·과장 표현, AI 논문형 연결어(따라서/결론적으로/정리하면)`,
    `- 같은 문단 반복`,
    ``,
    `[분량] 전체 2000~2500자. 누수탐지 업체가 작성한 안내 톤으로 간결하게.`,
    `[중복 금지] 같은 안내축을 여러 번 반복 나열하지 마세요. 한 번만 정리.`,
  ].filter((l) => l !== null && l !== undefined).join('\n');
}

// ── 섹션별 유저 프롬프트 ─────────────────────
function buildUserPrompt(region, treatment, sectionKey, aptName) {
  const kw = treatment.name;
  const subject = aptName ? `${region} ${aptName}` : region;
  const base =
    `🔒 주제 고정: "${kw}"${aptName ? ` / 대상 단지: "${aptName}"` : ''} 으로만 서술. 다른 단지·주제 혼용 금지.\n` +
    `🔒 화자는 "${region} 누수탐지 업체" 1인칭. 후기·체험담·시공후기·추천·보장·최저가 금지.\n` +
    `🔒 비용은 "영향 요소"로만, 정확한 금액 단정 금지.\n` +
    `🔒 "100% 해결/무조건" 등 해결 보장 표현 금지.\n\n`;

  const map = {
    intro:
      base +
      `[도입 — 상황 + 현장 진입]\n` +
      `전체 3문장. 첫 문장부터 ${aptName ? `"${aptName}"` : `"${region}"`} 현장에서 실제로 벌어진 상황 하나로 시작합니다. ` +
      `아래 서술은 전면 금지 — 누수가 어떤 현상인지 설명, 방치하면 생기는 피해, ${kw}의 일반적 필요성, 업종 소개. ` +
      `배경 설명 없이 상황 → 연락 → 현장 도착 순으로만 붙입니다. ` +
      `마지막 1문장은 의심 구간을 보러 이동하는 동작으로 닫습니다. 200자 내외.`,
    axis1:
      base +
      `[누수 원인·탐지 범위 안내]\n${subject} ${kw}에서 살펴보는 누수 원인과 탐지 범위를 설명하세요. ` +
      `배관 노후·방수층 손상·이음부 균열 등 어떤 원인을 확인하는지 정보로만. 250자 내외.`,
    axis2:
      base +
      `[현장 — 탐지 전개]\n` +
      `현장에서 누수 위치를 찾아가는 동안 이어지는 동작을 순서대로 씁니다. ` +
      `현장 확인 → 의심 구간 점검 → 누수 위치 특정 → 공사 범위 판단 순서를 지키되, ` +
      `각 단계를 항목으로 나열하지 말고 지금 손이 가고 눈이 가는 동작으로 서술하세요. ` +
      `단계마다 목적·원리·효과를 설명하지 않습니다. 250자 내외.`,
    infoblock:
      base +
      `[점검·확인 항목 정리]\n${kw} 관점에서 점검·확인할 항목을 목록으로 제시하세요. ` +
      `(누수 흔적·계량기 회전·공용배관 연관성·탐지 결과 등) 단정 없이 "확인할 점"으로. 250자 내외.`,
    axis3:
      base +
      `[탐지 장비 안내]\n${subject} ${kw}에 사용하는 탐지 장비를 설명하세요. ` +
      `열화상카메라·청음 탐지·가스 탐지·배관 내시경 등 장비별 역할을 정보로만. 250자 내외.`,
    axis4:
      base +
      `[현장 — 탐지 후 최종 확인]\n` +
      `탐지를 마친 뒤 현장에서 마지막으로 살펴보고 정리하는 장면을 씁니다. ` +
      `특정한 위치를 표시하고, 주변 마감과 젖은 자국 범위를 다시 짚고, 계량기 상태를 한 번 더 보는 동작 중심으로. ` +
      `누수의 원인이나 공사의 필요성을 설명하지 않습니다. ` +
      `"이러한 확인을 통해 ~합니다" 같은 정리·결론 문장으로 닫지 말고, 마지막도 확인 동작 그대로 끝냅니다. 250자 내외.`,
    closing:
      base +
      `[마무리]\n` +
      `총 3문장 이내, 150~250자. 이 분량을 절대 넘기지 마세요. 문단은 하나만 씁니다.\n` +
      `1문장 — 현장마다 상태가 달라 직접 봐야 안다는 점.\n` +
      `2문장 — 확인해 볼 수 있는 구체 행동 한 가지.\n` +
      `새 주제를 꺼내지 말고, 앞 문단을 다시 설명하지 마세요. 홍보 문장 금지.`,
  };
  return map[sectionKey] || base;
}

// ── 이미지 alt ──────────────────────────────
function getImageAlts(region, treatment, aptName) {
  const subject = aptName ? `${region} ${aptName}` : region;
  return [
    `${subject} 누수탐지 범위 안내`,
    `${region} 누수 탐지 절차 안내 자료`,
    `${region} 누수탐지 상담 안내`,
  ];
}

export { FORBIDDEN, buildSystemPrompt, buildUserPrompt, getImageAlts };
