// 트랙 선택 헬퍼
//   keyword/title에 트랙 힌트가 있으면 우선 선택
//   없으면 진료별 기본 트랙 선택
export function pickTrack(treatmentId, titleHint = '') {
  const tracks = TRACK_MAP[treatmentId];
  if (!tracks) return null;
  const trackKeys = Object.keys(tracks);

  // 제목 힌트 분석 — "수술/복강경/하이푸/미레나/LEEP/HRT/케겔" 등 단어로 분기
  const hint = String(titleHint).toLowerCase();
  if (hint.match(/지켜보|경과\s*관찰|6개월\s*추적|추적\s*관찰/)) {
    if (tracks.observe) return { key: 'observe', ...tracks.observe };
  }
  if (hint.match(/복강경|근종절제술|수술/) && treatmentId === 'uterine_fibroid') {
    if (tracks.procedure_laparo) return { key: 'procedure_laparo', ...tracks.procedure_laparo };
  }
  if (hint.match(/하이푸/) && tracks.procedure_hifu) {
    return { key: 'procedure_hifu', ...tracks.procedure_hifu };
  }
  if (hint.match(/미레나|호르몬|약물/) && tracks.medication) {
    return { key: 'medication', ...tracks.medication };
  }
  if (hint.match(/leep/i) && tracks.procedure) {
    return { key: 'procedure', ...tracks.procedure };
  }
  if (hint.match(/제왕절개/) && tracks.procedure_csection) {
    return { key: 'procedure_csection', ...tracks.procedure_csection };
  }
  if (hint.match(/자연분만|무통분만/) && tracks.procedure_natural) {
    return { key: 'procedure_natural', ...tracks.procedure_natural };
  }
  if (hint.match(/시술|수술/) && tracks.procedure) {
    return { key: 'procedure', ...tracks.procedure };
  }

  // 기본 트랙 우선순위 — observe > screening > medication > procedure*
  const priority = ['observe', 'screening', 'pregnancy', 'vaccine', 'medication',
                    'procedure', 'procedure_laparo', 'procedure_hifu',
                    'procedure_natural', 'procedure_csection'];
  for (const k of priority) {
    if (tracks[k]) return { key: k, ...tracks[k] };
  }
  // 폴백 — 첫 번째
  const k = trackKeys[0];
  return { key: k, ...tracks[k] };
}

