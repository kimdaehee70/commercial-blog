// lib/tankclean-prompts.js
// 저수조청소(tankclean) prompts — v1
// 방향: 정보형 + 관리안내 가이드형 / 대상·범위·절차·소독·주기·점검 축
// 화자 = {region} 저수조청소 업체 1인칭. 후기형·체험담·추천 금지.
// ★ 저수조청소 전용 절대 금지:
//    최저가/보장/업계 최고/1위/추천 단정 / 내돈내산 후기 / 100% 만족
// ★ 동의어: 저수조청소 ↔ 물탱크청소 — 자연 치환 허용(과밀 금지).
// 복제 베이스: cleaning-prompts.js (정보형 섹션 프롬프트 구조)

// ── 금칙어 (과장·후기·보장·추천) ───────────
const FORBIDDEN = [
  // 과장·광고
  '최저가', '무조건', '업계 최고', '1등 업체', '1위', '최고', '역대급', '초대박', '대박',
  '100% 만족', '완벽',
  // 보장·추천 (정보형 고정)
  '보장', '추천드립니다', '강력 추천', '추천 업체', '강추',
  // 후기·체험담
  '직접 해봤', '내돈내산', '후기입니다', '고객님 후기',
  // AI 논문형 연결어
  '따라서', '결론적으로', '정리하면',
];

// ── 분석축 라벨 (treatment.analysisAxis가 없을 때 fallback) ──
const DEFAULT_AXIS = ['청소 대상', '청소 범위', '작업 절차', '소독 과정', '점검 항목'];

// ── 시스템 프롬프트 ─────────────────────────
function buildSystemPrompt(region, treatment, aptName, aptMeta) {
  const kw = treatment.name;
  const axis = (treatment.analysisAxis && treatment.analysisAxis.length)
    ? treatment.analysisAxis : DEFAULT_AXIS;
  const subject = aptName ? `${region} ${aptName}` : region;
  // 단지 메타(생활권·역)가 있으면 입지 컨텍스트로 주입 → 단지 고유성 확보
  const metaLine = (aptMeta && (aptMeta.livingArea || aptMeta.station))
    ? `[단지 컨텍스트] ${aptName}은 ${aptMeta.livingArea || ""}${aptMeta.station ? `, ${aptMeta.station} 인근` : ""}입니다. 생활권·접근성은 이 정보를 자연스럽게 활용하되 저수조청소 안내가 주제임을 잊지 마세요.`
    : "";
  return [
    `당신은 ${region}에서 저수조청소를 안내하는 업체입니다.`,
    `화자는 "${region} 저수조청소 업체" 1인칭으로 고정합니다. 업체명·상호는 본문에 쓰지 않습니다.`,
    ``,
    metaLine || null,
    `[글의 성격]`,
    `- 정보 안내형 글입니다. ${aptName ? `"${aptName}" 저수조청소를` : `"${region}" 저수조청소를`} 청소 대상·범위·절차·소독·주기 기준으로 차분히 설명합니다.`,
    `- 후기형(체험담·내돈내산·방문기)은 쓰지 않습니다. 정보 안내 톤으로만.`,
    `- 손님이 "급수시설 관리·작업 절차·점검 항목"을 알 수 있게 돕는 가이드 톤.`,
    `- "저수조"와 "물탱크"는 같은 대상을 가리키는 동의어입니다. 문맥에 맞게 자연스럽게 사용하되 한 단어만 과도하게 반복하지 마세요.`,
    ``,
    `[저수조청소 절대 금지 — 반드시 지킬 것]`,
    `- 과장·광고 금지: "최저가/업계 최고/1위/100% 만족" 등 단정 금지.`,
    `- 보장·추천 단정 금지: "보장합니다/강력 추천" 금지. "확인할 점" 수준의 정보로만.`,
    `- 후기·체험담 금지: "직접 해봤/내돈내산/고객님 후기" 금지. 1인칭 체험 서술 금지.`,
    `- 비용 단정 금지: 정확한 금액 단정 금지. "용량·시설 유형·층수에 따라 달라지는 요소"로만.`,
    `- 효능·안전 과장 금지: "100% 위생/완전 멸균" 등 단정 금지. 관할 기준·정기 관리 안내 톤으로.`,
    ``,
    `[안내축 — 이 축으로 서술]`,
    axis.map((a) => `- ${a}`).join('\n'),
    ``,
    `[키워드]`,
    `- 핵심: "${kw}" 자연스럽게 반복(과밀 금지). 저수조/물탱크 동의어 분산 허용.`,
    `- 지역: "${subject}" 형태를 글 전체 3회 이하로. 이후 "이 시설/이 지역/현장" 자연 치환.`,
    ``,
    `[필수 요소]`,
    `- 청소 대상(저수조·고가수조·배관 연결부 등)`,
    `- 청소 범위(침전물·물때·내벽 세척)`,
    `- 작업 절차(급수 차단 → 잔수 배출 → 세척 → 소독 → 수질 확인)`,
    `- 점검 항목 또는 관리 주기·관리대장`,
    `- 비용은 "영향 요소"로만 설명(특정 금액 단정 금지).`,
    ``,
    `[금지]`,
    FORBIDDEN.map((w) => `- "${w}"`).join('\n'),
    `- 광고형·과장 표현, AI 논문형 연결어(따라서/결론적으로/정리하면)`,
    `- 같은 문단 반복`,
    ``,
    `[분량] 전체 2000~2500자. 저수조청소 업체가 작성한 안내 톤으로 간결하게.`,
    `[중복 금지] 같은 안내축을 여러 번 반복 나열하지 마세요. 한 번만 정리.`,
  ].filter((l) => l !== null && l !== undefined).join('\n');
}

// ── 섹션별 유저 프롬프트 ─────────────────────
function buildUserPrompt(region, treatment, sectionKey, aptName) {
  const kw = treatment.name;
  const subject = aptName ? `${region} ${aptName}` : region;
  const base =
    `🔒 주제 고정: "${kw}"${aptName ? ` / 대상 단지: "${aptName}"` : ''} 으로만 서술. 다른 단지·주제 혼용 금지.\n` +
    `🔒 화자는 "${region} 저수조청소 업체" 1인칭. 후기·체험담·추천·보장·최저가 금지.\n` +
    `🔒 비용은 "영향 요소"로만, 정확한 금액 단정 금지.\n` +
    `🔒 "저수조"·"물탱크"는 동의어. 자연스럽게 쓰되 한 단어만 과반복 금지.\n\n`;

  const map = {
    intro:
      base +
      `[도입 — 상황 + 현장 진입]\n` +
      `전체 3문장. 첫 문장부터 ${aptName ? `"${aptName}"` : `"${region}"`} 현장에서 관리자가 실제로 마주친 상황 하나로 시작합니다. ` +
      `아래 서술은 전면 금지 — 저수조가 어떤 시설인지 설명, 위생·건강에 미치는 영향, 관리가 왜 필요한지, ${kw}의 일반적 필요성. ` +
      `배경 설명 없이 상황 → 연락 → 현장 도착 순으로만 붙입니다. ` +
      `마지막 1문장은 현장에 도착해 저수조를 확인하러 가는 동작으로 닫습니다. 200자 내외.`,
    axis1:
      base +
      `[청소 대상·범위 안내]\n${subject} ${kw}의 청소 대상과 범위를 설명하세요. ` +
      `저수조 내벽·바닥·맨홀·배관 연결부 등 어디를 다루는지 정보로만. 250자 내외.`,
    axis2:
      base +
      `[현장 — 작업 전개]\n` +
      `${kw} 작업이 진행되는 동안 현장에서 이어지는 동작을 순서대로 씁니다. ` +
      `급수 차단 → 잔수 배출 → 침전물 제거 → 내벽 세척 → 소독 → 수질 확인 순서를 지키되, ` +
      `각 단계를 항목으로 나열하지 말고 지금 손이 가는 동작으로 서술하세요. ` +
      `단계마다 목적·효과를 설명하지 않습니다. 250자 내외.`,
    infoblock:
      base +
      `[점검·확인 항목 정리]\n${kw} 관점에서 예약 전·작업 후 확인할 항목을 목록으로 제시하세요. ` +
      `(용량·급수 차단 시간·소독 범위·수질 확인 등) 단정 없이 "확인할 점"으로. 250자 내외.`,
    axis3:
      base +
      `[소독 과정·관리 주기]\n${subject} ${kw}의 소독 과정과 관리 주기를 설명하세요. ` +
      `세척 후 소독 → 헹굼 → 관리대장 기록 흐름으로. 구체 주기는 관할 기준 확인 안내로. 250자 내외.`,
    axis4:
      base +
      `[현장 — 작업 후 최종 점검]\n` +
      `작업을 마친 뒤 현장에서 마지막으로 살펴보는 장면을 씁니다. ` +
      `맨홀 잠금 상태·내벽 잔존물·오버플로우 통로·급수 재개 후 물 상태를 눈으로 확인하는 동작 중심으로. ` +
      `청소의 필요성이나 효과를 설명하지 않습니다. ` +
      `"이러한 점검을 통해 ~을 확인합니다" 같은 정리·결론 문장으로 문단을 닫지 말고, 마지막도 확인 동작 그대로 끝냅니다. 250자 내외.`,
    closing:
      base +
      `[마무리]\n` +
      `총 3문장 이내, 150~250자. 이 분량을 절대 넘기지 마세요. 문단은 하나만 씁니다.\n` +
      `1문장 — 시설마다 상태가 달라 현장에서 봐야 안다는 점.\n` +
      `2문장 — 확인해 볼 수 있는 구체 행동 한 가지.\n` +
      `새 주제를 꺼내지 말고, 앞 문단을 다시 설명하지 마세요. 홍보 문장 금지.`,
  };
  return map[sectionKey] || base;
}

// ── 이미지 alt ──────────────────────────────
function getImageAlts(region, treatment, aptName) {
  const subject = aptName ? `${region} ${aptName}` : region;
  return [
    `${subject} 저수조청소 범위 안내`,
    `${region} 저수조 작업 절차 안내 자료`,
    `${region} 저수조청소 상담 안내`,
  ];
}

export { FORBIDDEN, buildSystemPrompt, buildUserPrompt, getImageAlts };
