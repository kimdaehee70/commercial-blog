export const FORBIDDEN = FILM_FORBIDDEN;

// ── Scene 조회 ──────────────────────────────────────────
//   엔진(resolveScene) 우선. REGISTRY 미등록 시점에도 안전하도록 로컬 테이블로 축퇴한다.
function getScene(cat) {
  const s = resolveScene("film", cat);
  if (s && (s.arrive.length || s.work.length)) return s;
  const t = LOCAL_SCENES[cat] || LOCAL_SCENES[LOCAL_DEFAULT] || {};
  return {
    arrive: Array.isArray(t.arrive) ? t.arrive : [],
    work: Array.isArray(t.work) ? t.work : [],
    basis: Array.isArray(t.basis) ? t.basis : [],
  };
}

// ── 현장정보 문맥 문자열 ────────────────────────────────
//   siteBlock 이 소유한 값(단지명·평형)을 프롬프트 문맥으로만 전달한다.
//   본문 삽입은 핸들러의 insertSiteBeforeHashtags 가 담당(중복 서술 방지).
function siteLine(ctx) {
  const s = (ctx && ctx.site) || {};
  if (!s.siteName) return "";
  const size = s.siteSize ? ` ${s.siteSize}` : "";
  return `- 현장: ${s.siteName}${size} (현장명은 도입부에 1회까지만. 반복 금지)\n`;
}

// ── [세션136 · SINK-FILM-RECOVERY-01] 적용 cat 게이트 ────
//   ★ 지시 9항 "다른 film 카테고리 및 타 업종 행동 변경 금지" 준수 장치.
//     이 Set 밖의 cat 은 프롬프트가 수술 전과 바이트 단위로 동일하다.
//     다른 cat 으로 넓히려면 여기에 cat 이름 1개만 추가한다(다른 코드 무수정).
const RECOVERY_CATS = new Set(["싱크대필름"]);
function recoveryOn(cat) { return RECOVERY_CATS.has(String(cat || "")); }

// ── [세션136 · SINK-FILM-RECOVERY-01/A] Facts 계약 ───────
//   Facts 있음 → 실제 사례형 허용(입력값 범위 안에서만)
//   Facts 없음 → 정보형·조건형. 특정 현장을 목격·작업한 것처럼 쓰지 않는다.
//   ★ basis(spine/scenes/film.js)는 하드코딩 상수다. 사용자 사실이 아니므로 Facts에 넣지 않는다.
//     실측(S136): 싱크대필름 basis 1개 고정 → 전건이 「부풀음→수증기→건조」 동일 장면으로 복제됐다.
export function hasFacts(ctx) {
  const c = ctx || {};
  const s = c.site || {};
  return !!(
    String(s.siteName || "").trim() ||
    String(c.material || "").trim() ||
    String(c.surface || "").trim() ||
    String(c.baseGrade || "").trim() ||
    String(c.workScope || "").trim() ||
    String(c.existingCondition || "").trim()
  );
}

// ── [세션136/C] 신규 입력 2축 — 실제 시공범위 / 실제 기존상태 ──
//   미입력이면 빈 문자열 → 프롬프트에 아무것도 붙지 않는다(부작용 0).
function factsLine(ctx) {
  const c = ctx || {};
  const sc = String(c.workScope || "").trim();
  const cd = String(c.existingCondition || "").trim();
  let out = "";
  if (sc) out += `- 실제 시공 범위: ${sc} (여기 적힌 범위만 씁니다. 없는 부위를 추가하지 않습니다)\n`;
  if (cd) out += `- 실제 기존 상태: ${cd} (관찰된 사실은 이것뿐입니다. 다른 손상·증상을 만들지 않습니다)\n`;
  return out;
}

