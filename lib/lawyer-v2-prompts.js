import { DIRECTION, FORBIDDEN } from "./lawyer-prompts";
import { LAWYER_KEYPOINTS, LAWYER_SITUATIONS, LAWYER_MISTAKES, LAWYER_CLOSING } from "./lawyer-v2-data";

// [세션41] AI 상투어 — 화자를 지우는 표현. 프롬프트 금지 + 핸들러 후처리 이중 차단.
const AI_CLICHE = [
  "도움이 되길 바랍니다", "유익합니다", "원활하게", "차근차근", "차근히",
  "명확하게 이해", "신속한 진단", "함께 고민", "적극 지원", "효과적으로 대응",
  "막막함을 느끼는 것이 당연", "혼란스러울 수 있습니다",
  // [세션41-2] 관측 보강 — concern 첫 문단이 여전히 '공감 서술'로 시작하던 표현들.
  "여러 가지 걱정이 생길 수 있습니다", "걱정이 생길 수 있습니다",
  "불안이 클 수 있습니다", "불안감이 클 수 있습니다",
  "명확한 방향이 필요합니다", "당황스러울 수 있습니다",
  "어려움을 겪고 계신다면", "방향을 잡아보시는 것이 좋습니다",
  "전문적인 법률 조언을 받으며", "도움이 될 수 있습니다",
  // [세션41-3] 관측 3차 — 변형형까지 차단. 어미만 바꿔 회귀하던 표현들.
  "불안할 수 있습니다", "불안감이 있을 수 있습니다",
  "확실한 정보가 부족한 상황입니다", "정보가 부족한 상황입니다",
  "명확하지 않아", "막막할 수 있습니다",
  "최적의 전략을 수립합니다", "최적의 전략",
  "돕겠습니다", "도와드리겠습니다", "함께 하겠습니다",
  "대응 전략을 세우는 데 큰 영향", "큰 영향을 미칩니다",
  "주의가 필요합니다", "인지해야 합니다",
];

function buildSystemPromptV2(region, treatment) {
  const dir = DIRECTION[treatment.id] || {};
  const kw = dir.keyword || treatment.name;
  return [
    `당신은 ${region} 소재 법률사무소의 변호사입니다. 상담을 앞둔 사람에게 직접 설명하듯 씁니다.`,
    ``,
    `[이 글을 읽는 사람]`,
    `- "${kw}" 문제에 지금 막 직면했습니다. 절차 설명서를 원하는 게 아닙니다.`,
    `- 실제 질문: 내가 이 상황에 해당하나 / 지금 뭘 하면 안 되나 / 무엇부터 하나 / 뭘 준비하나.`,
    ``,
    `[글의 성격]`,
    `- 정보형. 후기·성공사례 금지. 결과 보장·약속 금지(승소·무죄 등 단정 표현 전면 금지).`,
    `- 각 문단은 서로 다른 일을 합니다. 앞 문단에서 한 말을 다른 표현으로 다시 하지 않습니다.`,
    ``,
    `[문체 — 반드시 지킬 것]`,
    `- 인사말·서론 금지. 첫 문장부터 상황으로 들어갑니다.`,
    `- "첫째·둘째·셋째" 기계적 나열 금지. 자연스러운 문단.`,
    `- 홍보성 표현 금지. AI 논문형 연결어(따라서/결론적으로/정리하면) 금지.`,
    `- 다음 상투어 사용 금지:`,
    AI_CLICHE.map((w) => `  · "${w}"`).join("\n"),
    `- "중요합니다" "필요합니다" "주의가 필요합니다"로 문장을 끝내는 습관 금지.`,
    `  대신 무엇이 어떻게 달라지는지 씁니다. (X) "합의가 중요합니다" (O) "합의 여부에 따라 처분이 갈립니다"`,
    `- "~하는 데 큰 영향을 미칩니다" "~을 인지해야 합니다" 같은 평가 문장 금지.`,
    ``,
    `[키워드] 핵심 "${kw}" 5회 이상. 지역 "${region} ${kw} 변호사" 형태 2~3회.`,
    ``,
    `[비용] 범위·산정 방식으로만. 특정 금액·항목 단정 금지. "상담 시 안내" 수준.`,
    ``,
    `[금지어]`,
    FORBIDDEN.map((w) => `- "${w}"`).join("\n"),
    ``,
    `[분량] 전체 1800~2400자. 담담한 실무 안내 톤.`,
  ].join("\n");
}

function buildUserPromptV2(region, treatment, sectionKey) {
  const dir = DIRECTION[treatment.id] || {};
  const kw = dir.keyword || treatment.name;
  const full = `${region} ${kw} 변호사`;
  const kp = LAWYER_KEYPOINTS[treatment.id] || [];
  const sit = LAWYER_SITUATIONS[treatment.id];
  const mis = LAWYER_MISTAKES[treatment.id] || LAWYER_MISTAKES._default;

  const base =
    `🔒 집중 사건: "${kw}" 으로만 서술. 다른 사건 유형 혼용 금지.\n` +
    `🔒 화자는 변호사(사무소 1인칭). 결과보장·홍보 표현 금지.\n` +
    `🔒 AI 상투어 금지: 도움이 되길 / 유익합니다 / 원활하게 / 차근차근 / 함께 고민합니다.\n\n`;

  const map = {
    // ① concern — 상황문으로 즉시 시작. 인사말·공감 나열 금지.
    concern:
      base +
      `[① 지금 상황]\n` +
      `소제목 없이 본문으로 바로 시작합니다.\n` +
      `"${kw}" 문제로 검색한 사람이 지금 놓인 구체적 상황을 2~3문장으로 씁니다.\n` +
      `참고 상황: ${dir.concern || ""}\n` +
      `🚫 인사말·자기소개 금지.\n` +
      `🚫 감정·심리 서술 전면 금지: "걱정이 생길 수 있습니다" "불안이 클 수 있습니다" "막막합니다" ` +
      `"혼란스러울 수 있습니다" "당황스러울 수 있습니다" — 이런 문장을 단 한 개도 쓰지 마세요.\n` +
      `🚫 "명확한 방향이 필요합니다" 같은 글 예고·메타 문장 금지.\n` +
      `🚫 절차·자료 언급 금지(뒤 섹션 소관).\n` +
      `✅ 대신 '무슨 일이 벌어졌는지'와 '지금 실제로 무엇이 정해지지 않았는지'를 사실로 씁니다.\n` +
      `   예: "경찰에서 출석하라는 연락을 받았는데, 언제 무슨 말을 해야 하는지는 알려주지 않습니다."\n` +
      `   예: "돈을 빌려준 지 시간이 지났고, 상대는 연락을 피합니다. 이게 사기인지 단순 미변제인지는 아직 정해진 게 없습니다."\n` +
      `첫 문장은 상황 자체로 시작합니다. 200자 내외.`,

    // ② firstMove — 입장 분기 + 판단 기준. 자료·절차 금지.
    firstMove:
      base +
      (kp.length ? `🔑 이 사건의 판단 포인트: ${kp.join(" · ")}\n\n` : "") +
      `[② 먼저 확인할 것]\n` +
      `"${kw}" 상황에서 지금 판단해야 할 핵심을 설명합니다.\n` +
      (sit
        ? `⚑ 검색자 입장이 갈립니다. 두 입장이 각각 지금 뭘 확인해야 하는지 나눠 짚어주세요(자연스러운 문단으로).\n` +
          `   · ${sit.split}\n   · ${sit.hintA}\n   · ${sit.hintB}\n`
        : "") +
      `위 판단 포인트를 검색자의 실제 질문 형태로 풀어줍니다.\n` +
      `🚫 준비 자료 목록 금지(⑤ 소관). 🚫 절차 단계 나열 금지(⑥ 소관). 🚫 상담 진행 설명 금지(④ 소관).\n` +
      `🚫 "증거를 모으는 것이 중요합니다" 류의 일반론 금지 — 무엇을 어떻게 보는지 구체적으로.\n` +
      `400자 내외.`,

    // ③ mistake — 전문직 차별 섹션. 실수만.
    mistake:
      base +
      `[③ 지금 하면 안 되는 것]\n` +
      `"${kw}" 상황에서 초기에 흔히 저지르는 실수를 짚어줍니다. 왜 문제가 되는지 한 줄씩 덧붙입니다.\n` +
      `다음을 재료로 삼되, 그대로 옮기지 말고 이 사건 맥락에 맞게 풀어 쓰세요:\n` +
      mis.map((m) => `   · ${m}`).join("\n") + "\n" +
      `🚫 해결책·대응 방법 설명 금지(② ④ 소관). 하면 안 되는 것과 그 이유만.\n` +
      `🚫 겁주는 표현·단정 금지. 담담하게.\n` +
      `300자 내외.`,

    // ④ consult — 진행 관점만.
    consult:
      base +
      `[④ 상담에서 확인하는 것]\n` +
      `상담 자리에서 실제로 오가는 이야기를 씁니다. 의뢰인이 무엇을 묻고, 변호사가 무엇을 되묻는지.\n` +
      `${dir.effect || ""} 관점.\n` +
      `🚫 "파악합니다 → 설명합니다 → 수립합니다" 식 업무 절차 나열 절대 금지. 사무적 설명체 금지.\n` +
      `🚫 "최적의 전략" "정확한 사실관계" 같은 관용구 금지.\n` +
      `🚫 [세션41-4] 개인 1인칭 금지: "저는" "제가" "저희는" 을 쓰지 마세요.\n` +
      `   (관측: 명예훼손 생성에서 "제가 법적 절차를 설명합니다" 등장 → 화자가 사무소에서 개인으로 흔들림.)\n` +
      `   주어 없이 서술하거나 "상담에서는 ~을 먼저 봅니다" 형태로 씁니다.\n` +
      `🚫 판단 기준 재설명 금지(②). 🚫 자료 목록 금지(⑤). 🚫 절차 나열 금지(⑥).\n` +
      `✅ 대신 상담에서 실제로 나오는 질문을 씁니다.\n` +
      `   예: "당시에 먼저 손이 나간 쪽이 어디였는지, 그걸 본 사람이 있었는지부터 묻습니다.\n` +
      `        본인은 방어였다고 생각해도 상대 진술과 어긋나면 그 지점을 먼저 정리해야 합니다."\n` +
      `2~3문장. 200자 내외.`,

    // ⑤ documents — 목록만.
    documents:
      base +
      `[⑤ 미리 준비하면 좋은 자료]\n` +
      `"${kw}" 상황에서 상담 전에 정리해 두면 좋은 자료를 목록으로 제시합니다.\n` +
      `각 항목은 "- 자료명 — 왜 필요한지 한 줄" 형식. 4~5개.\n` +
      `🚫 판단 포인트·상담 내용·절차 재설명 금지. 목록만.\n` +
      `250자 내외.`,

    // ⑥ process — 참고 수준.
    process:
      base +
      `[⑥ 이후 진행 흐름]\n` +
      `"${kw}" 사건이 이후 어떻게 흘러가는지 3문장 이내로만 씁니다.\n` +
      `🚫 교과서식 절차 설명 금지("증거와 증언을 통해 사실관계를 규명하고" 같은 문장).\n` +
      `🚫 번호 나열 금지. 🚫 앞에서 다룬 판단·자료·상담 재언급 금지.\n` +
      `✅ 각 단계에서 '당사자에게 실제로 무슨 일이 생기는지'만 짧게.\n` +
      `   예: "조사가 끝나면 검찰이 기소 여부를 정합니다. 여기서 정해진 진술이 이후 재판까지 그대로 따라갑니다."\n` +
      `150자 내외. 반드시 짧게.`,

    // ⑦ closing — 재요약 금지.
    closing:
      base +
      `[⑦ 마무리]\n` +
      (LAWYER_CLOSING[treatment.id]
        ? `✅ 이 사건의 마무리에서만 짚을 것(반드시 이 내용을 첫 문장에 녹여 쓰세요):\n` +
          `   "${LAWYER_CLOSING[treatment.id]}"\n` +
          `   → 그대로 복사하지 말고 자연스럽게 문장으로 풀어 쓰세요.\n`
        : "") +
      `그 뒤에 "${full}" 초기 상담 안내 1~2문장.\n` +
      `🚫 절차·판단·자료 재요약 금지(앞에서 전부 다룸). 🚫 "운영자" 표현 금지.\n` +
      `🚫 다음 상투구 금지: "차근차근" / "하나씩 정리하면 됩니다" / "어려움을 겪고 계신다면" / ` +
      `"방향을 잡아보시는 것이 좋습니다" / "전문적인 법률 조언을 받으며".\n` +
      `🚫 사무소 자기지시 종결 금지: "돕겠습니다" / "도와드리겠습니다" / "함께 하겠습니다" / ` +
      `"마련할 수 있도록 돕겠습니다" — 이 패턴은 모든 글이 똑같아집니다.\n` +
      `✅ 마무리는 상담이 어떤 자리인지만 담담히 알립니다. 약속·다짐 없이.\n` +
      `   예: "${full} 상담에서는 지금 남아 있는 자료를 놓고 무엇이 정해지고 무엇이 남았는지부터 봅니다."\n` +
      `120자 내외.`,
  };
  return map[sectionKey] || base;
}

export { buildSystemPromptV2, buildUserPromptV2, AI_CLICHE };
