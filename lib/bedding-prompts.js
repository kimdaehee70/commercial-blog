// ── 섹션별 유저 프롬프트 빌더 (매뉴얼 PART3) ────────────────────
// 7섹션 정보형. 각 섹션에 activeKeyword 강제 주입.
export function buildBeddingPrompt({ section, treatmentId, treatmentName, region = "용인", store = BEDDING_STORE_DEFAULT }) {
  const dir = BEDDING_DIRECTION[treatmentId] || {};
  const activeKeyword = treatmentName;
  const fullKeyword = `${region} ${treatmentName}`;

  const isPillow = ["funcpillow", "custompillow", "iupillow"].includes(treatmentId);

  const lock = [
    `🔒 집중 키워드: "${activeKeyword}" 으로만 서술. 다른 침구 종류 혼용 금지.`,
    `🔒 복합 키워드: "${fullKeyword}" 는 글 전체 3회 이하 — 이 섹션에서 남발 금지.`,
    `🔒 화자: 이브자리 ${store} 매장. 구매자 화자/후기 표현 금지.`,
    section === "intro"
      ? `🔒 인사말("안녕하세요. 이브자리 ${store}입니다.")은 이 섹션 첫 문장에서 단 한 번만.`
      : `🔒 이 섹션은 인사말("안녕하세요" 등) 없이 곧바로 내용으로 시작. 매장 소개·인사 반복 금지.`,
    `🔒 분량: 이 섹션은 핵심만 간결하게. 앞 섹션에서 다룬 내용 반복·재설명 금지.`,
  ].join("\n");

  const sectionSpec = {
    intro: `[섹션: 찾는 이유]\n"안녕하세요. 이브자리 ${store}입니다."로 시작. ${dir.hook || `${treatmentName}을 찾는 분들이 많습니다`} 맥락으로, 이 글이 ${treatmentName} 선택 전 확인할 점을 정리하는 글임을 안내. 후킹은 검색 상황(${dir.concern || "정보 탐색"})으로. 2~3문장.`,
    check: `[섹션: 먼저 확인할 요소]\n${treatmentName}을 고를 때 가장 먼저 보는 기준 2~3가지를 정보형으로. ${dir.effect || "구성·소재·관리 기준"} 중심. 항목별로 "왜 보는지"까지 짧게.${isPillow ? ` 베개는 특히 '목·어깨 높이와의 맞음(경추 지지)', '잠버릇(옆으로/바로 눕기)에 따른 높이', '복원력 유지' 세 가지를 확인 기준으로 반드시 포함.` : ""}`,
    material: `[섹션: 소재/기능]\n${treatmentName}의 소재·기능 차이를 비교 설명. 통기/무게/보온/복원력 등 구체 속성으로. 특정 제품 광고 금지, 일반 정보로.${isPillow ? ` 베개 소재는 메모리폼·라텍스·구스(다운)·폴리 등으로 구분해, 각 소재의 지지력·복원 속도·통기·세탁 가능 여부 차이를 정보형으로 정리.` : ""}`,
    usage: `[섹션: 사용환경]\n어떤 사용 환경(가족 구성·수면 습관·방 환경)에서 어떤 선택이 맞는지 기준 제시. 단정 금지, "환경에 따라 다릅니다" 어조.`,
    season: `[섹션: 계절/생활패턴]\n${treatmentName}을 계절·생활 패턴과 연결해 교체 시점·관리 주기 정보 제공. 세탁·보관 시 확인할 점 포함.`,
    compare: `[섹션: 비교 확인요소]\n${treatmentName}과(와) 인접 선택지의 차이를 확인 기준 중심으로 정리. 우열 평가/순위/점수 금지. "이런 경우엔 이쪽을 보는 편" 정도.`,
    outro: `[섹션: 마무리]\n정리 후, 직접 보고 비교하려면 이브자리 ${store} 매장에서 확인할 수 있다고 안내. 구매 강요/할인/추천 표현 금지. 매장 방문 안내까지만. "발행은 매장에서 직접" 원칙과 무관하게, 본문은 방문 안내로 마침.`,
  };

  return [
    sectionSpec[section] || sectionSpec.check,
    "",
    lock,
  ].join("\n");
}

