// 입주청소(cleaning) prompts — v2 (Construction Scene Spine 적용)
// 방향: 현장형 Scene(intro/axis1/axis3) + 정보형(axis2/axis4/infoblock/closing) 역할 분리
// 화자 = {region} 입주청소 업체 1인칭. 후기형·체험담·추천 금지.
// ★ 변경 범위: prompt 표현만. FLOW / playConfig / handler / data 구조 무수정.
//
// Scene Spine (실측 기반):
//   도착 → 조사 → 발견 → 판단 → 작업 → 확인 → 다음 공간
//   상위권 글의 공통점 = "공간을 설명한다"가 아니라 "공간을 조사한다".
//
// 역할 분리:
//   intro  = 도착 / 겉보기 확인 / 첫 발견
//   axis1  = 현장 조사 동선 (현관→거실→창틀→…)
//   axis3  = Scene 반복 (확인→발견→판단→작업→확인→다음 공간)
//   axis2  = 비용 영향 요소  (정보형 유지)
//   axis4  = 예약 전 확인    (정보형 유지)
//   infoblock / closing      (정보형 유지)
//
// ★ V3 학습 반영: [필수 요소] 전역 요구 → [요소 배분 원칙]으로 전환.
//   각 요소는 해당 섹션에서만 소비. 마지막 섹션 누락 보충 금지(closing 폭주 차단).
// ★ V3 학습 반영: 규칙 안의 예시 문구는 본문으로 새어나온다.
//   → 예시로 든 표현은 반드시 금지 목록에 함께 등재.

