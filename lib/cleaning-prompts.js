// ── 분석축 라벨 (treatment.analysisAxis가 없을 때 fallback) ──
const DEFAULT_AXIS = ['청소 범위', '비용 영향 요소', '진행 순서', '예약 전 확인', '체크포인트'];

// ── Scene 동선 ──
//   [세션60] cat별 동선 토큰은 lib/spine/scenes/cleaning.js 단일 소유.
//   기존 prompts 내부 SCENE_ROUTE 상수는 이중 소스가 되어 제거함.
const DEFAULT_ROUTE = ['현장 도착', '세대 전체 상태 확인', '창호 오염 확인', '작업 구역 구분'];

// ── 오염 요소 — Scene 안에서 "발견"되는 방식으로만 사용 ──
const SOIL_POOL = [
  '석고 분진', '실리콘 자국', '목재 톱밥', '시멘트 가루', '창틀 레일 먼지',
  '몰딩 위 먼지', '환기구 먼지', '조명 위 먼지', '배수구 이물질', '타일 줄눈 먼지',
];

function getRoute(treatment) {
  const s = getSceneSpine(treatment && treatment.cat);
  return (s.arrive && s.arrive.length) ? s.arrive : DEFAULT_ROUTE;
}

