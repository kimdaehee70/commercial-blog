export function buildRadioV2Prompt(section, treatment, region) {
  switch (section) {
    case "concern":       return _concern(treatment, region);
    case "visitTrigger":  return _visitTrigger(treatment, region);
    case "examination":   return _examination(treatment, region);
    case "examDecision":  return _examDecision(treatment, region);
    case "resultReading": return _resultReading(treatment, region);
    case "examProcess":   return _examProcess(treatment, region);
    case "closing":       return _closing(treatment, region);
    default:              return "";
  }
}

