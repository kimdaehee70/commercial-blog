import {
  PAINT_FORBIDDEN,
  PAINT_PHOTO_POOL,
  formatSymptom,
  getPartNote,
} from "./paint-data.js";
import { resolveScene } from "./spine/sceneSpine.js";
import { SCENES as LOCAL_SCENES, DEFAULT_CAT as LOCAL_DEFAULT } from "./spine/scenes/paint.js";

export const FORBIDDEN = PAINT_FORBIDDEN;

// ── Scene 조회 ──────────────────────────────────────────
//   엔진(resolveScene) 우선. REGISTRY 미등록 시점에도 안전하도록 로컬 테이블로 축퇴한다.
function getScene(cat) {
  const s = resolveScene("paint", cat);
  if (s && (s.arrive.length || s.work.length)) return s;
  const t = LOCAL_SCENES[cat] || LOCAL_SCENES[LOCAL_DEFAULT] || {};
  return {
    arrive: Array.isArray(t.arrive) ? t.arrive : [],
    work: Array.isArray(t.work) ? t.work : [],
    basis: Array.isArray(t.basis) ? t.basis : [],
  };
}

// 발견·원인군 — paint 는 원인군이 판단 축이라 문맥 재료로 함께 전달한다.
function contextLine(ctx) {
  const sym = formatSymptom(ctx && ctx.symptom);
  const pt = getPartNote(ctx && ctx.part);
  let out = "";
  if (sym) out += `- 접수된 상태: ${sym} (이 상태에서 출발합니다. 다른 증상을 새로 만들지 않습니다)\n`;
  if (pt) out += `- 점검 원인군: ${pt.label} — ${pt.note} (이 문장을 그대로 옮기지 말고 판단 근거로만 쓴다)\n`;
  return out;
}

// ── 시스템 프롬프트 ─────────────────────────────────────
