// ── SYSTEM PROMPT (V2) ──────────────────────────
export function buildSystemPromptV2(region, treatment) {
  const axis = getAdminAxis(treatment.id);
  const axisLine = {
    application:
      "이 업무는 행정청에 자격·등록·인증·설립을 '신청'하는 업무다. 신청인이 지켜야 할 신고기한이 있는 업무가 아니다. 존재하지 않는 신고기한을 만들지 마라.",
    appeal:
      "이 업무는 이미 내려진 처분에 '불복'하는 업무다. 청구기간(90일)이 신청인에게 걸린 기한이며, 이를 놓치면 본안 판단 없이 각하될 수 있다. '신고기한'이라는 용어를 쓰지 마라.",
    document:
      "이 업무는 문서를 '작성·발송'하는 업무다. 행정청에 신고하거나 신청하는 절차가 아니다. 신고기한·접수기한·심사·인용 같은 관청 절차 용어를 쓰지 마라. 소멸시효는 별개 개념이다.",
  }[axis];

  return [
    `너는 「${region} 지역 행정사사무소」의 안내 글을 쓰는 실무 행정사다.`,
    `업무: ${treatment.name}. ${treatment.summary || ""}`,
    ``,
    `[업무 성격 — 반드시 지킬 것]`,
    `- ${axisLine}`,
    ``,
    `[화자 규칙]`,
    `- 1인칭 기관형 화자. 절차를 담담하게 안내한다.`,
    `- 고객·의뢰인 후기, 성공 사례, 수임 자랑을 쓰지 않는다.`,
    `- 사무소 상호를 본문에 반복 노출하지 않는다.`,
    ``,
    `[결과 약속 금지 — 가장 중요]`,
    `- "승인됩니다 / 인가됩니다 / 등록이 완료됩니다 / 인용됩니다 / 취소됩니다 / 구제받을 수 있습니다" 같은 결과 단정을 절대 쓰지 않는다.`,
    `- "요건만 충족하면 승인", "서류만 갖추면 통과" 같은 조건부 결과 약속도 금지.`,
    `- 결과는 심사·검토 대상이다. "검토됩니다 / 검토 대상이 됩니다 / 판단이 달라집니다"로 서술한다.`,
    axis === "appeal"
      ? `- 심판·심리 용어는 이 업무(불복)에서만 쓴다. "심리 대상 / 재결" 사용 가능.`
      : `- ★ "심리 대상 / 재결 / 인용" 은 행정심판(불복) 전용 용어다. 이 업무에서는 절대 쓰지 마라. "검토 대상"으로 쓴다.`,
    ``,
    `[작성 원칙]`,
    `- 정보형. 광고 문구(최고·완벽·강추) 금지.`,
    `- 지역명+업무 결합은 글 전체 3회 이하. 이후 "이 절차 / 해당 업무"로 치환.`,
    `- AI 논문형 연결어(따라서·결론적으로·정리하면) 금지.`,
    `- 제공된 재료의 사실관계를 벗어나 기한·수치·요건을 창작하지 않는다.`,
  ].join("\n");
}

// ── USER PROMPT (섹션별 · 축 분기) ────────────────
export function buildUserPromptV2(region, treatment, sectionKey) {
  const kw = treatment.name;
  const id = treatment.id;
  const axis = getAdminAxis(id);
  const common = `지역: ${region} / 업무: ${kw} / 업무유형: ${axis}`;

  const map = {
    intro: [
      common,
      `[도입] 아래 상황을 1문단으로 환기한다.`,
      `상황: ${SITUATIONS[axis]}`,
      `홍보·후기·과장 금지. 사무소명 노출 금지. 2~3문장.`,
    ].join("\n"),

    overview: [
      common,
      `[제도 개요] ${kw}이(가) 어떤 제도이고 누가 대상인지 정보형으로 설명한다.`,
      `근거 제도 · 대상 · 기본 성격 중심. 2~3문단.`,
      axis === "document"
        ? `주의: 이 업무는 행정청 신청 절차가 아니다. 문서의 성격과 용도를 설명한다.`
        : `주의: 결과를 약속하는 문장을 쓰지 않는다. 등록·인증의 효과를 "법적 지위를 확보한다 / 자격을 얻게 된다"처럼 단정하지 말고, "등록 절차의 대상이 되며 기준에 따라 심사가 진행된다"로 서술한다.`,
    ].join("\n"),

    deadline: [
      common,
      `[기한] 아래 재료를 근거로 기한을 안내한다. 재료에 없는 기한·날짜를 만들지 마라.`,
      `재료: ${getDeadline(id, axis)}`,
      axis === "appeal"
        ? `핵심: 청구기간이 지나면 각하될 수 있다는 점을 분명히 한다. 기산점(처분서 수령일)을 먼저 확인하라고 안내한다.`
        : axis === "document"
        ? `핵심: 이 업무에는 신고기한·접수기한이 없다. 기한이 없다는 사실 자체를 안내하고, 대신 소멸시효나 계약상 통보기간이 실제 기준임을 설명한다. '신고기한'이라는 표현을 쓰지 마라.`
        : `핵심: 신청인이 지켜야 할 신고기한이 아니라, 신청 시기 제약과 행정청 처리기간의 구분을 안내한다.`,
      `2문단 이내.`,
    ].join("\n"),

    documents: [
      common,
      `[준비서류] 아래 재료를 근거로 제출·준비 서류를 안내한다. 재료에 없는 서류를 창작하지 마라.`,
      `재료: ${getDocuments(id)}`,
      `필수 항목과 상황에 따라 달라지는 항목을 구분해 서술한다. 목록 나열이 아니라 왜 필요한지가 드러나게 쓴다. 2~3문단.`,
    ].join("\n"),

    criteria: [
      common,
      `[요건·기준] 아래 재료를 근거로, 무엇이 검토 대상인지를 안내한다.`,
      `재료: ${getCriteria(id)}`,
      `★ 절대 규칙: 결과를 약속하지 마라.`,
      `- 금지: "요건을 충족하면 승인됩니다", "서류가 갖춰지면 등록이 완료됩니다", "인용됩니다", "취소됩니다", "구제받을 수 있습니다"`,
      `- 금지: "법적 지위를 확보할 수 있습니다", "자격을 얻게 됩니다", "법적 인정을 받습니다" — 등록의 효과를 단정하는 표현`,
      axis === "appeal"
        ? `- 허용: "심리 대상입니다", "검토 대상이 됩니다", "쟁점이 됩니다", "판단이 달라집니다"`
        : `- 허용: "검토 대상이 됩니다", "심사 대상입니다", "보완 요구가 이어집니다", "판단이 달라집니다"`,
      axis !== "appeal"
        ? `- ★ "심리 대상 / 재결 / 인용"은 행정심판 전용 용어다. 이 업무에서는 쓰지 마라.`
        : ``,
      axis === "document"
        ? `- ★ 이 업무는 행정청이 심사하는 절차가 아니다. "적법성 판단 / 심사 대상 / 승인 여부 / 인용" 같은 관청 심사 프레임을 쓰지 마라. 이런 개념이 "없다"고 설명할 필요도 없다. 처음부터 다른 프레임으로 쓴다 — 실무에서 갈리는 지점은 "기재 내용의 명확성 / 사실관계와의 일치 / 근거 자료의 일관성"이다.`
        : ``,
      `이 섹션은 검색자가 "되나요"를 묻는 자리다. 답은 "이런 항목이 검토된다"이지 "된다/안 된다"가 아니다.`,
      `2~3문단.`,
    ].join("\n"),

    process: (() => {
      const p = getAdminProcess(id);
      return [
        common,
        `[진행 절차] 아래 재료의 단계를 순서대로 안내한다. 재료에 없는 단계를 추가하지 마라.`,
        `단계: ${p.steps}`,
        `종결 지점: ${p.end}`,
        axis === "document"
          ? `주의: 이 업무는 행정청 접수·심사·재결 절차가 없다. 관청 절차 용어를 넣지 마라.`
          : `주의: 결과 단정을 쓰지 않는다. 절차의 흐름만 서술한다.`,
        `2~3문단.`,
      ].join("\n");
    })(),

    closing: [
      common,
      `[마무리] 아래 취지를 1문단으로 담담하게 마무리한다.`,
      `취지: ${CLOSING[axis]}`,
      `글 전체 재요약 금지. 결과 보장·과장 금지. 목록 사용 금지. 2~3문장.`,
    ].join("\n"),
  };

  return map[sectionKey] || map.overview;
}

