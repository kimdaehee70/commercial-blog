const COMMERCIAL_FIRST_PERSON_PATTERNS = [
  [/(?:^|[\s,.])저는\s+/g, " "],
  [/(?:^|[\s,.])제가\s+/g, " "],
  [/(?:^|[\s,.])내가\s+/g, " "],
  [/(?:^|[\s,.])나는\s+/g, " "],
  [/(?:^|[\s,.])저도\s+/g, " "],
];

// ============================================================
// 5. commercial 텍스트 자동 정제 함수
// ============================================================
function commercialClean(text) {
  let result = text;

  // [1] 가격 패턴 치환 (먼저)
  COMMERCIAL_PRICE_PATTERNS.forEach(([from, to]) => {
    result = result.replace(from, to);
  });

  // [2] 후기형 동사 → 정보형 동사 (먼저 변환해야 잔존 단어 제거 가능)
  COMMERCIAL_VERB_CONVERSION.forEach(([from, to]) => {
    result = result.replace(from, to);
  });

  // [3] 1인칭 정리
  COMMERCIAL_FIRST_PERSON_PATTERNS.forEach(([from, to]) => {
    result = result.replace(from, to);
  });

  // [4] 잔존 금지어 제거 (변환되지 않은 표현)
  COMMERCIAL_FORBIDDEN.forEach(w => {
    result = result.replace(new RegExp(w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "g"), "");
  });

  // [5] 후속 정리 — 변환 후 어색해진 문장 보정
  result = result
    // 빈 어절 정리: "결과가 . " 같은 잔존 → 제거
    .replace(/\s+\.\s+\./g, ".")
    .replace(/\s+\./g, ".")
    .replace(/\.\s*\./g, ".")
    // 빈 따옴표·괄호
    .replace(/\(\s*\)/g, "")
    .replace(/"\s*"/g, "")
    // 의미 없어진 토막 문장 ("결과가 .", "결과는 .")
    .replace(/[가-힣]+가\s*\./g, "")
    .replace(/[가-힣]+는\s*\./g, "")
    // 이중 공백·줄바꿈
    .replace(/\s{3,}/g, " ")
    .replace(/\n{3,}/g, "\n\n")
    // 문장 시작이 마침표·쉼표인 경우
    .replace(/^[\s.,]+/, "")
    .replace(/\n\s*[\s.,]+/g, "\n")
    .trim();

  return result;
}

