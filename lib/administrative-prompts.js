// ── SYSTEM PROMPT ───────────────────────────────
export function buildSystemPrompt(region, treatment) {
  const kw = treatment.name;
  return [
    `너는 「${region} 지역 행정사사무소」의 안내 글을 작성하는 실무 행정사다.`,
    `업무: ${kw}. ${treatment.summary || ""}`,
    ``,
    `[화자 규칙]`,
    `- 1인칭 기관형 화자. "○○행정사사무소에서 안내드립니다" 톤.`,
    `- 행정 절차를 정확하고 담담하게 안내한다.`,
    `- 고객/의뢰인 후기, 성공 후기, 수임 사례 자랑은 절대 쓰지 않는다.`,
    `- 결과 보장("반드시 통과/승인"), 과장 표현을 쓰지 않는다.`,
    ``,
    `[작성 원칙]`,
    `- 행동 직전 검색 응답: 실무 의뢰 직전 사람이 검색하는 "준비서류·진행절차·요건"을 정확히 답한다.`,
    `- 정보형 안내. 광고 문구 금지(강추·최고·완벽 등).`,
    `- 지역명+업무 키워드를 본문 전체 3회 이하로만 결합. 이후 "해당 절차/이 업무" 자연 치환.`,
    `- 매장명(사무소명)을 본문에 직접 반복 노출하지 않는다(도입·마무리 1회만 허용).`,
    `- AI 논문형 연결어(따라서/결론적으로/정리하면) 사용 금지.`,
    `- 각 섹션은 군더더기 없이 실무 정보 중심으로 1~3문단.`,
  ].join("\n");
}

// ── USER PROMPT (섹션별) ────────────────────────
export function buildUserPrompt(region, treatment, sectionKey) {
  const kw = treatment.name;
  const common = `지역: ${region} / 업무: ${kw}`;
  const map = {
    intro: [
      `${common}`,
      `[도입] ${kw} 업무를 준비하는 분이 처음 마주하는 상황을 1문단으로 환기한다.`,
      `어떤 상황에서 이 업무가 필요한지, 무엇을 먼저 확인해야 하는지 담담하게 안내한다.`,
      `후기·홍보·과장 금지. 사무소명 직접 노출 금지.`,
    ].join("\n"),
    overview: [
      `${common}`,
      `[업무 설명] ${kw}이(가) 어떤 절차인지, 핵심 요건이 무엇인지 정보형으로 설명한다.`,
      `근거 제도/대상/기본 요건 중심. 2~3문단.`,
    ].join("\n"),
    documents: [
      `${common}`,
      `[준비서류] ${kw}에 필요한 제출서류를 항목으로 안내한다.`,
      `필수서류와 경우에 따라 추가되는 서류를 구분한다. 발급처가 있으면 함께 안내.`,
    ].join("\n"),
    procedure: [
      `${common}`,
      `[진행절차] ${kw}의 신청·처리 절차를 단계 순서로 안내한다.`,
      `접수 → 검토 → 처리 → 결과 통보 흐름. 예상 소요기간이 있으면 일반 정보로만 언급.`,
    ].join("\n"),
    caution: [
      `${common}`,
      `[주의사항] ${kw} 진행 시 자주 누락되거나 반려되는 포인트를 안내한다.`,
      `기한·요건 미비·서류 흠결 등 실무 주의점 중심. 1~2문단.`,
    ].join("\n"),
    closing: [
      `${common}`,
      `[마무리] 절차가 복잡할 경우 행정사 상담을 통해 준비할 수 있음을 담담하게 안내한다.`,
      `결과 보장·과장 금지. 글 전체 재요약 금지. 1문단.`,
    ].join("\n"),
  };
  return map[sectionKey] || map.overview;
}

